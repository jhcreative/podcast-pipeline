"""
test_card03_captions.py — CARD-03 caption assembly, About parsing, and gates.

Run: python3 test_card03_captions.py   (plain asserts, no pytest needed)

Covers CARD-03 acceptance criteria:
  AC2 fixed shape assembled in code        → test_assembled_shape_is_exact
  AC3 intro sourced from About only        → test_about_parser_*
  AC4 pending bio marked, never composed   → test_bio_pending_*
  AC5 every gate is a hard failure         → test_gate_*

Discipline (same as test_ty02 / test_title01): make_captions is PURE at import —
stdlib plus quote_source — so it is tested directly with no stubs. The one impure
path, anthropic_client.compose_card_captions, is imported lazily inside main() and
is NOT exercised here; it needs a live API key and is CARD-03's remaining
acceptance criterion.

Fixtures are inline rather than read from Episodes/, which is gitignored — a test
that needs artifacts a fresh clone lacks is a test that quietly stops running. The
two apple_summary shapes below are transcribed from the real E24 and E25 files.
"""

import os
import sys
from pathlib import Path

WORKTREE = Path(__file__).resolve().parent.parent  # the repo root: tests/ is one level down
sys.path.insert(0, str(WORKTREE / "quote_cards"))

import make_captions as mc  # noqa: E402


# ── fixtures ───────────────────────────────────────────────────────────────────

# E25's shape: a real bio under a level-2 heading, followed by a horizontal rule.
ABOUT_REAL = """# Apple/Spotify Show Notes — E25

## Show notes

Something about the episode.

---

## About Juniper Larkspirelle

Juniper Larkspirelle is a Plant Medicine Guide and community gardener, a synthetic
guest invented for testing, who teaches small groups to grow, dry and brew the
herbs on their own windowsills and porches, one season at a time.

---

## Generated by Podcast Manager
"""

# E24's shape: the guest never filed an intake form, so the bio is a placeholder
# followed by an explanation of why. This is a real, recurring state — not an edge case.
ABOUT_PENDING = """## About Bettany Strandwhistle

`[BIO PENDING — supplied manually by Heather/John before publish]`

**Why this is a placeholder:** Bettany Strandwhistle does not appear in the Podcast Guest
Info responses sheet. PM also swept Heather's Gmail — no results.

---
"""

CLEAN_TAGS = ["#GenXHitsMenopause", "#MenopauseHealth", "#GenXWomen"]
QUOTE = "Normal blood work does not always mean optimum health."


def _caption(opening="Your labs can be normal and you can still feel wrong.",
             intro="Juniper Larkspirelle is a Plant Medicine Guide and Herbalist.",
             guest="Juniper Larkspirelle", ep=25, tags=None):
    return mc.assemble(opening, intro, guest, ep, tags or CLEAN_TAGS)


# ── About parsing ──────────────────────────────────────────────────────────────


def test_about_parser_real_bio():
    guest, about = mc.extract_about(ABOUT_REAL)
    assert guest == "Juniper Larkspirelle", guest
    assert about.startswith("Juniper Larkspirelle is a Plant Medicine Guide"), about[:60]
    # Must stop at the horizontal rule, not swallow the generator footer.
    assert "Generated by Podcast Manager" not in about
    print("  ok  About parser: name + body, stops at the rule")


def test_about_parser_heading_levels():
    """ADR-0008 made hand-edited Drive artifacts authoritative, so the parser has to
    read what a human typed — including a bare 'About X' with no heading marks."""
    for heading in ("## About Juniper Larkspirelle", "About Juniper Larkspirelle",
                    "#### About Juniper Larkspirelle", "### about Juniper Larkspirelle"):
        guest, about = mc.extract_about(f"{heading}\n\nA real bio paragraph here that "
                                        f"is comfortably longer than the length floor.")
        assert guest == "Juniper Larkspirelle", (heading, guest)
        assert about.startswith("A real bio"), (heading, about[:40])
    print("  ok  About parser: tolerates heading level and case")


def test_about_parser_absent():
    guest, about = mc.extract_about("# Show notes\n\nNo About section at all.\n")
    assert guest is None and about is None
    print("  ok  About parser: absent section returns None, does not guess")


# E29's real shape: John hand-edits the summary in Drive, the Docs export renders
# the horizontal rule as underscores, and the "About <Guest>" heading is gone.
ABOUT_HEADINGLESS = """# Apple/Spotify Show Notes — E29

Heather sits down with Dr. Thessaly Brindlequist to talk hormones.

________________

Dr. Thessaly Brindlequist is a Chiropractic Physician and a synthetic guest, invented
for testing, known to her invented patients as "the kitchen-table doctor."

She earned her doctorate from an invented college at the age of 26, becoming the
youngest graduate in her year.
"""


def test_about_parser_headingless_falls_back_to_the_name():
    """ADR-0008 makes hand-edited summaries authoritative, and hand edits lose the
    heading. Without this fallback E29 reported a pending bio while a real one sat
    in the file."""
    guest, about = mc.extract_about(ABOUT_HEADINGLESS, "Dr. Thessaly Brindlequist")
    assert guest == "Dr. Thessaly Brindlequist", guest
    assert about.startswith("Dr. Thessaly Brindlequist is a Chiropractic Physician"), about[:60]
    assert "youngest graduate" in about, "the bio's later paragraphs must survive"
    assert "Heather sits down" not in about, "must not grab the hook intro"
    assert "____" not in about, "divider rows must be dropped"
    assert mc.bio_is_pending(about) is False
    print("  ok  About parser: heading-less bio found by the guest's name")


def test_about_parser_headingless_needs_the_hint():
    guest, about = mc.extract_about(ABOUT_HEADINGLESS, None)
    assert guest is None and about is None
    print("  ok  About parser: no hint, no guess")


# ── pending-bio detection (AC4) ────────────────────────────────────────────────


def test_bio_pending_real_placeholder():
    _, about = mc.extract_about(ABOUT_PENDING)
    assert mc.bio_is_pending(about) is True, about[:80]
    print("  ok  pending bio: E24's real placeholder detected")


def test_bio_pending_real_bio_is_not():
    _, about = mc.extract_about(ABOUT_REAL)
    assert mc.bio_is_pending(about) is False
    print("  ok  pending bio: a real bio is not flagged")


def test_bio_pending_empty_and_stub():
    assert mc.bio_is_pending(None) is True
    assert mc.bio_is_pending("") is True
    assert mc.bio_is_pending("TBD") is True          # too short to be a bio
    print("  ok  pending bio: empty / missing / stub all treated as pending")


# ── assembled shape (AC2) ──────────────────────────────────────────────────────


def test_assembled_shape_is_exact():
    """The connect and listen lines are fixed copy written by code, not the model.
    If this golden changes, it changed deliberately — ADR-0013."""
    got = mc.assemble("Opening line.", "Guest intro.", "Juniper Larkspirelle", 25, CLEAN_TAGS)
    expected = (
        "Opening line.\n"
        "\n"
        "Guest intro.\n"
        "\n"
        "Connect with Juniper Larkspirelle at [ADD @HANDLE]\n"
        "Listen to E25 on Apple Podcasts & Spotify — link in bio.\n"
        "\n"
        "#GenXHitsMenopause #MenopauseHealth #GenXWomen\n"
    )
    assert got == expected, repr(got)
    print("  ok  assembled caption is byte-identical to the golden shape")


def test_connect_line_names_the_guest():
    got = mc.assemble("O.", "I.", "Dr. Thessaly Brindlequist", 29, CLEAN_TAGS)
    assert "Connect with Dr. Thessaly Brindlequist at [ADD @HANDLE]" in got
    assert "Listen to E29 on Apple" in got
    print("  ok  connect line carries the guest's name; listen line the episode")


# ── gates (AC5) ────────────────────────────────────────────────────────────────


def _expect_fail(fn, needle):
    try:
        fn()
    except SystemExit as e:
        assert needle.lower() in str(e).lower(), f"wrong reason: {e}"
        return
    raise AssertionError(f"expected a hard failure mentioning {needle!r}")


def test_gate_passes_clean_caption():
    mc.assert_caption_wellformed(_caption(), CLEAN_TAGS, QUOTE, "clean")
    print("  ok  gate: a clean caption passes")


def test_gate_hashtag_count():
    """ADR-0007's cap, asserted at generation time — the check CAP-01 asked for on
    the reel captions and never got."""
    for tags in (["#GenXHitsMenopause", "#A"],
                 ["#GenXHitsMenopause", "#A", "#B", "#C", "#D"]):
        _expect_fail(
            lambda t=tags: mc.assert_caption_wellformed(
                _caption(tags=t), t, QUOTE, "count"),
            "3–4")
    print("  ok  gate: rejects fewer than 3 and more than 4 hashtags")


def test_gate_requires_show_tag():
    tags = ["#MenopauseHealth", "#GenXWomen", "#HormoneHealth"]
    _expect_fail(
        lambda: mc.assert_caption_wellformed(_caption(tags=tags), tags, QUOTE, "show"),
        "show tag")
    print("  ok  gate: rejects a set with no show tag")


def test_gate_malformed_hashtag():
    tags = ["#GenXHitsMenopause", "MenopauseHealth", "#two words"]
    _expect_fail(
        lambda: mc.assert_caption_wellformed(_caption(tags=tags), tags, QUOTE, "malformed"),
        "malformed")
    print("  ok  gate: rejects a missing # and an embedded space")


def test_gate_rejects_url():
    """Captions here never carry platform links, and a model-written URL can be
    subtly wrong — this publisher has supplied wrong Apple URLs before."""
    bad = _caption(opening="Listen at https://podcasts.apple.com/x")
    _expect_fail(
        lambda: mc.assert_caption_wellformed(bad, CLEAN_TAGS, QUOTE, "url"),
        "url")
    print("  ok  gate: rejects any URL")


def test_gate_rejects_music_credit():
    """The Uppbeat credit belongs to the reels' licensed track. A quote card is
    silent; crediting it here would be a false attribution (ADR-0013)."""
    bad = _caption(opening="🎵 from #uppbeat — Show Me by Daze")
    _expect_fail(
        lambda: mc.assert_caption_wellformed(bad, CLEAN_TAGS, QUOTE, "music"),
        "music")
    print("  ok  gate: rejects a music/audio credit on a silent card")


def test_gate_rejects_blank_connect_line():
    bad = _caption().replace(mc.SOCIAL_PLACEHOLDER, "")
    _expect_fail(
        lambda: mc.assert_caption_wellformed(bad, CLEAN_TAGS, QUOTE, "handle"),
        "placeholder")
    print("  ok  gate: rejects a connect line with neither handle nor placeholder")


def test_gate_accepts_a_real_handle():
    """Once John fills the placeholder in, the caption must still pass."""
    filled = _caption().replace(mc.SOCIAL_PLACEHOLDER, "@juniperlarkspirelle")
    mc.assert_caption_wellformed(filled, CLEAN_TAGS, QUOTE, "filled")
    print("  ok  gate: a filled-in handle passes")


def test_gate_rejects_opening_that_restates_the_quote():
    """The quote is already on the image; repeating it burns the one visible line."""
    bad = _caption(opening=QUOTE)
    _expect_fail(
        lambda: mc.assert_caption_wellformed(bad, CLEAN_TAGS, QUOTE, "restate"),
        "restates")
    print("  ok  gate: rejects an opening that restates the quote verbatim")


# ── novel-term review (the check the gates cannot be) ──────────────────────────


def test_novel_terms_flags_borrowed_episode_topics():
    """E31's first real run: the model wrote "including estrogen, the menstrual
    cycle, and perimenopause" — all true of the episode, none of it in a bio that
    says "female-specific biology" and names joint pain. Nothing inflated, but
    sharpen-don't-extend was broken, and no structural gate can see it."""
    about = ("Dr. Saffi Velloquin is a phytopharmacist specializing in cannabinoid "
             "science and female-specific physiology. Her career began in an "
             "invented botanical laboratory, where she led a small study of "
             "plant extracts for joint pain.")
    intro = ("Dr. Saffi Velloquin is a phytopharmacist whose work spans cannabinoid "
             "science and female-specific biology — including estrogen, the menstrual "
             "cycle, and perimenopause.")
    novel = mc.novel_terms(intro, about)
    for term in ("estrogen", "menstrual", "perimenopause"):
        assert term in novel, (term, novel)
    print(f"  ok  novel terms: borrowed episode topics surfaced ({', '.join(novel)})")


def test_novel_terms_quiet_on_faithful_paraphrase():
    about = ("Dr. Saffi Velloquin is a phytopharmacist and women's health strategist "
             "with a doctorate in plant chemistry. She spent over a decade across "
             "laboratory research and patient education.")
    intro = ("Dr. Saffi Velloquin is a phytopharmacist and women's health strategist "
             "with a doctorate in plant chemistry, spanning a decade across "
             "laboratory research and patient education.")
    novel = mc.novel_terms(intro, about)
    assert novel == [] or novel == ["spanning"], novel
    print("  ok  novel terms: a faithful paraphrase stays quiet")


# ── runner ─────────────────────────────────────────────────────────────────────


def main() -> int:
    tests = [
        test_about_parser_real_bio,
        test_about_parser_heading_levels,
        test_about_parser_absent,
        test_about_parser_headingless_falls_back_to_the_name,
        test_about_parser_headingless_needs_the_hint,
        test_bio_pending_real_placeholder,
        test_bio_pending_real_bio_is_not,
        test_bio_pending_empty_and_stub,
        test_assembled_shape_is_exact,
        test_connect_line_names_the_guest,
        test_gate_passes_clean_caption,
        test_gate_hashtag_count,
        test_gate_requires_show_tag,
        test_gate_malformed_hashtag,
        test_gate_rejects_url,
        test_gate_rejects_music_credit,
        test_gate_rejects_blank_connect_line,
        test_gate_accepts_a_real_handle,
        test_gate_rejects_opening_that_restates_the_quote,
        test_novel_terms_flags_borrowed_episode_topics,
        test_novel_terms_quiet_on_faithful_paraphrase,
    ]
    failed = 0
    print("CARD-03 caption assembly + gates — test run")
    for t in tests:
        try:
            t()
        except AssertionError as e:
            failed += 1
            print(f"  FAIL {t.__name__}: {e}")
        except Exception as e:  # noqa: BLE001
            failed += 1
            import traceback
            print(f"  ERROR {t.__name__}: {type(e).__name__}: {e}")
            traceback.print_exc()
    print(f"\n{len(tests) - failed} passed, {failed} failed (of {len(tests)})")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
