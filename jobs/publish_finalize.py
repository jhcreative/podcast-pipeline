def _apply_phase2_completion(
    ep: dict,
    *,
    apple_url: str,
    spotify_url: str,
    mm_url: str,
    blog_post_url: str,
    message_id: str,
    today: str,
    links_pending: bool = False,
) -> None:
    """
    Mark a publication_schedule entry as Phase-2 complete, merging NON-DESTRUCTIVELY.

    Extracted as a pure function so the merge rules are testable without a Drive or
    Gmail round-trip — the rules are where the bugs live, not the file I/O.

    Three rules, each from a real incident:

    • **Never clobber a known value with an empty one.** The reprocess path carries no
      `mm_url` and no `message_id` (there is no publisher email any more — ADR-0011).
      Writing those through unconditionally would erase what an earlier genuine
      email-triggered run recorded.

    • **Preserve `actual_live_date` once set.** The old code stamped *today* every
      time. For the email trigger that was right — the notification arrived the day
      the episode went live. For a recovery it is wrong: E30 went live 2026-07-09 and
      was recovered on 2026-07-21, and stamping the recovery date would have quietly
      falsified the publication record.

    • **`status` and `pipeline_done` are the point.** They are set unconditionally;
      that is what makes the entry agree with the job that just succeeded.
    """
    ep["status"] = "done"
    ep["pipeline_done"] = True
    ep["blog_post_url"] = blog_post_url
    ep["apple_url"] = apple_url or ep.get("apple_url")
    ep["spotify_url"] = spotify_url or ep.get("spotify_url")
    ep["mm_url"] = mm_url or ep.get("mm_url")
    ep["mission_matters_email_id"] = message_id or ep.get("mission_matters_email_id")
    ep["actual_live_date"] = ep.get("actual_live_date") or today
    ep.pop("pending_mm_context", None)
    # TRIG-02: say so on the record while the links are still the show pages. The caller decides (this
    # function stays pure: test_sched01 runs it in isolation).
    ep["episode_links_pending"] = bool(links_pending)
    ep["notes"] = (ep.get("notes") or "") + f" | Phase 2 complete {today}" + (
        " (episode links pending)" if ep["episode_links_pending"] else "")


