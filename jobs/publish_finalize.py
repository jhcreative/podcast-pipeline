def _find_file_by_pattern(files: list[dict], pattern: str, flags=0) -> dict | None:
    """Find the first file whose name matches a regex pattern."""
    rx = re.compile(pattern, flags)
    for f in files:
        if rx.search(f["name"]):
            return f
    return None
