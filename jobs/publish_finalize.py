def _drive_delete_all_by_name(files: list[dict], name: str) -> int:
    """Delete all Drive items (files or folders) matching name. Returns count deleted."""
    from googleapiclient.discovery import build as _build
    from google_auth import drive_credentials as _drive_creds
    svc = _build("drive", "v3", credentials=_drive_creds(), cache_discovery=False)
    deleted = 0
    for f in files:
        if f["name"] == name:
            try:
                svc.files().delete(fileId=f["id"]).execute()
                deleted += 1
            except Exception as exc:
                logger.warning("publish_finalize: could not delete %r (%s): %s", name, f["id"], exc)
    return deleted


# ── main entry point ────────────────────────────────────────────────────────────


def run(job_id: int, episode_id: str, payload: dict) -> None:
    """
    PUBLISH_FINALIZE — Legacy Publisher live email → full content production.

    payload (gmail trigger):
      {"trigger": "gmail", "message_id": "...", "thread_id": "...",
       "subject": "...", "sender": "..."}

    payload (drive_resume trigger — visuals just added):
      {"trigger": "drive_resume", "apple_url": "...", "spotify_url": "...",
       "mm_url": "...", "episode_number": 26, "message_id": "..."}
    """
    logger.info("publish_finalize start — job_id=%d payload=%s", job_id, payload)
    try:
        _run_pipeline(job_id, payload)
    except PermanentFailure:
        raise  # already logged; worker stops retries
    except content_gates.GateFailure as exc:
        # A content gate said no (guest not featured, reel backgrounds don't match the speakers, …). Retrying
        # can't change the answer: it used to be retried 5× silently, recomposing the FAQ each time, with no
        # word to John. Tell him once, with the gate's own reason, and stop. Fix the input, then re-touch an image.
        ep = payload.get("episode_number")
        _alert(f"E{ep if ep is not None else '?'}: Phase 2 stopped — fix and re-drop an image", f"{exc}\n")
        raise PermanentFailure(f"gate: {exc}") from exc
    except Exception as exc:
        logger.exception("publish_finalize: unhandled error: %s", exc)
        raise  # worker retries with exponential back-off


def _run_pipeline(job_id: int, payload: dict) -> None:
    """Inner pipeline. Called by run(); errors propagate up."""
    trigger = payload.get("trigger", "gmail")
    from_email = False

    # reels_only: re-render + replace reel mp4s, touch nothing else.
    # Only the reprocess trigger sets it (see tools/reprocess_episode.py --reels-only).
    reels_only = bool(payload.get("reels_only"))

    # ── Step 1 — Parse MM email (or read from resume payload) ──────────────────
    run_ledger.step("1", "parse_email")
    if trigger == "reprocess":
        apple_url = payload.get("apple_url", "")
        spotify_url = payload.get("spotify_url", "")
        mm_url = payload.get("mm_url", "")
        episode_number = int(payload["episode_number"])
        message_id = ""
        if not reels_only and not (apple_url and spotify_url):
            raise PermanentFailure(
                "PUBLISH_FINALIZE reprocess: apple_url and spotify_url are required "
                "unless reels_only is set (they feed the blog/captions compose steps)"
            )
        logger.info(
            "publish_finalize: reprocess path — E%d apple=%s spotify=%s reels_only=%s",
            episode_number, apple_url, spotify_url, reels_only,
        )
    elif trigger == "visuals":
        # TRIG-02: the images arrived. Links are whatever the operator passed (none, normally) → show pages.
        apple_url = payload.get("apple_url") or _SHOW_APPLE_URL
        spotify_url = payload.get("spotify_url") or _SHOW_SPOTIFY_URL
        mm_url = payload.get("mm_url", "")
        episode_number = int(payload["episode_number"])
        message_id = ""
        logger.info(
            "publish_finalize: visuals path — E%d (episode links %s)",
            episode_number, "pending: show pages used" if _links_pending(apple_url, spotify_url) else "given",
        )
    elif trigger in ("drive_resume", "drive_changes_resume"):
        # drive_changes has always enqueued "drive_changes_resume"; only "drive_resume" was recognised, so a
        # resume fell into the e-mail branch below. Both names land here now.
        apple_url = payload["apple_url"]
        spotify_url = payload["spotify_url"]
        mm_url = payload.get("mm_url", "")
        episode_number = int(payload["episode_number"])
        message_id = payload.get("message_id", "")
        logger.info(
            "publish_finalize: drive_resume path — E%d apple=%s spotify=%s",
            episode_number, apple_url, spotify_url,
        )
    else:
        # Gmail trigger — parse the publisher "Episode is Live" email.
        # All assumptions about the (drifting) publisher contract — sender
        # allowlist, reply guard, HTML-only body, mangled Apple ids, missing EP
        # number — live in publisher_email.py. See that module's header.
        from_email = True  # TRIG-03: route on how this job started, not on the trigger's name (Toby F-5)
        message_id = payload.get("message_id", "")
        if not message_id:
            raise PermanentFailure("PUBLISH_FINALIZE payload missing message_id")

        msg = gmail_client.get_message(message_id)
        sender = gmail_client.get_header(msg, "from")
        subject = gmail_client.get_header(msg, "subject")
        in_reply_to = gmail_client.get_header(msg, "in-reply-to")

        # TRIG-03 AC-10: the From line proves nothing on its own (Legacy Publisher publishes DMARC
        # p=NONE, so a forged From is delivered). Google's verdict decides, checked here as well as in
        # the webhook, because a job can be retried or enqueued by hand.
        authentic, why = publisher_email.authenticated_sender(msg.get("payload", {}).get("headers", []))
        if not authentic:
            raise PermanentFailure(f"PUBLISH_FINALIZE: sender {sender!r} not authenticated: {why}")
        if not publisher_email.is_publish_notification(subject, in_reply_to=in_reply_to):
            raise PermanentFailure(
                f"PUBLISH_FINALIZE: {subject!r} is not an original publish notification "
                f"(reply/forward, or missing 'episode is live')"
            )

        # Body is now HTML-only — read text AND html so the listen links resolve.
        text_body = gmail_client.extract_plain_text(msg)
        html_body = gmail_client.extract_html(msg)
        urls = publisher_email.extract_publish_urls(text_body, html_body)
        apple_url, spotify_url, mm_url = urls["apple_url"], urls["spotify_url"], urls["mm_url"]

        # Identify the episode WITHOUT requiring an EP number (title match, then
        # single-awaiting-publish fallback). None ⇒ ambiguous ⇒ fail safe.
        pub_schedule_early = _read_json(_PUB_SCHEDULE_PATH)
        ep_match = publisher_email.identify_episode(
            subject, f"{text_body}\n{html_body}", pub_schedule_early.get("episodes", [])
        )

        missing = []
        if not apple_url:
            missing.append("Apple Podcasts URL")
        if not spotify_url:
            missing.append("Spotify URL")
        if not ep_match:
            missing.append("matching episode (by EP number or title)")
        if missing:
            raise PermanentFailure(
                f"PUBLISH_FINALIZE: could not process publish email: {', '.join(missing)}. "
                f"subject={subject!r}"
            )

        episode_number = int(ep_match["episode_number"])

        logger.info(
            "publish_finalize: parsed publish email — E%d apple=%s spotify=%s mm=%s",
            episode_number, apple_url, spotify_url, mm_url,
        )

    # ── Step 2 — Identify episode in pub_schedule ──────────────────────────────
    run_ledger.step("2", "identify")
    pub_schedule = _read_json(_PUB_SCHEDULE_PATH)
    ep_entry = None
    for ep in pub_schedule.get("episodes", []):
        if ep.get("episode_number") == episode_number and ep.get("drive_folder_id"):
            ep_entry = ep
            break

    if not ep_entry:
        if trigger == "reprocess":
            # Reprocess path: episode predates pub_schedule or was never recorded.
            # Find the Drive folder by episode code prefix and build a stub entry.
            ep_folder = drive_client.find_episode_folder(f"E{episode_number}")
            if not ep_folder:
                raise PermanentFailure(
                    f"PUBLISH_FINALIZE reprocess: no Drive folder found for E{episode_number} "
                    f"— expected folder named E{episode_number}-* in the episodes Drive folder"
                )
            ep_entry = {
                "episode_number": episode_number,
                "episode_code": f"E{episode_number}",
                "season_episode_code": "TBD",
                "slug": "",
                "drive_folder_id": ep_folder["id"],
                "episode_title": "TBD",
                "guest_name": "Guest",
                "guest_email": "",
                "calendar_event_id": "",
            }
            logger.info(
                "publish_finalize: reprocess stub entry for E%d — Drive folder %s",
                episode_number, ep_folder["id"],
            )
        else:
            raise PermanentFailure(
                f"PUBLISH_FINALIZE: no pub_schedule entry with drive_folder_id for episode {episode_number}"
            )

    episode_code = ep_entry["episode_code"]          # "E26"
    run_ledger.bind(episode=episode_code)
    episode_title = ep_entry.get("episode_title", "TBD")
    season_ep_code = ep_entry.get("season_episode_code", "S?E?")
    slug = ep_entry.get("slug", "")
    episode_folder_id = ep_entry["drive_folder_id"]
    calendar_event_id = ep_entry.get("calendar_event_id", "")
    guest_name = ep_entry.get("guest_name") or "Guest"
    guest_email = ep_entry.get("guest_email") or ""

    episode_folder_url = f"https://drive.google.com/drive/folders/{episode_folder_id}"
    logger.info(
        "publish_finalize: episode identified — %s (%s) title=%r guest=%s",
        episode_code, season_ep_code, episode_title, guest_name,
    )

    # ── TRIG-03 — a publisher email for an episode Phase 2 already finished ────
    # Decided HERE, in the worker, against the schedule as it stands when the job runs: the single
    # worker serialises this behind any visuals run. A finished episode never runs Phase 2 again
    # (E33, job 142, 2026-10-08: a second thank-you draft, re-rendered reels, regenerated captions).
    run_ledger.step("2b", "route_late_email")
    if not (from_email and ep_entry.get("pipeline_done")):
        run_ledger.skipped("not a late email for a finished episode")
    if from_email and ep_entry.get("pipeline_done"):
        still_show = _links_pending(ep_entry.get("apple_url") or "", ep_entry.get("spotify_url") or "")
        if not (ep_entry.get("episode_links_pending") or still_show):
            note = f"publisher email for {episode_code}: Phase 2 already done with episode links — nothing to do"
            logger.info("publish_finalize: %s", note)
            _prepend_standup(episode_code, f"[NO-OP] {note}")
            return
        _links_only(
            ep_entry=ep_entry, episode_code=episode_code, episode_number=episode_number,
            apple_url=apple_url, spotify_url=spotify_url, mm_url=mm_url, message_id=message_id,
            subject=subject, body_text=f"{text_body}\n{html_body}",
        )
        return

    # ── Step 3 — Check visual assets ──────────────────────────────────────────
    run_ledger.step("3", "visuals")
    folder_files = drive_client.list_folder(episode_folder_id)
    tile_file = _find_visual(folder_files, "tile")
    reel_file = _find_visual(folder_files, "reel")

    if not tile_file or not reel_file:
        missing_visuals = []
        if not tile_file:
            missing_visuals.append(f"E{episode_number}-firstname-tile.jpg")
        if not reel_file:
            missing_visuals.append(f"E{episode_number}-firstname-reel.jpg")

        msg_body = (
            f"Episode {episode_code} ({episode_title}) is live on Apple + Spotify "
            f"but Phase 2 cannot run until these files are in the Drive episode folder:\n\n"
            + "\n".join(f"  • {f}" for f in missing_visuals)
            + f"\n\nDrive folder: {episode_folder_url}\n\n"
            f"Once you drop them in, the pipeline resumes automatically."
        )

        # Notify John by email
        gmail_client.send_pipeline_alert(
            to=_PIPELINE_ALERT_EMAIL,
            subject=f"Action needed: {episode_code} visuals missing — {episode_title}",
            body=msg_body,
        )

        # Write standup entry
        _prepend_standup(
            episode_code,
            f"[BLOCKED] Waiting for tile.jpg + reel.jpg before Phase 2 can run.\n"
            f"  Missing: {', '.join(missing_visuals)}\n"
            f"  Drive folder: {episode_folder_url}"
        )

        # Store mm_context in pub_schedule so the Drive watch resume path can find it
        for ep in pub_schedule.get("episodes", []):
            if ep.get("episode_number") == episode_number and ep.get("drive_folder_id"):
                ep["status"] = "waiting_for_visuals"
                ep["pending_mm_context"] = {
                    "apple_url": apple_url,
                    "spotify_url": spotify_url,
                    "mm_url": mm_url,
                    "episode_number": episode_number,
                    "message_id": message_id,
                    "received_at": datetime.now(timezone.utc).isoformat(),
                }
                break
        pub_schedule["updated_at"] = datetime.now(timezone.utc).isoformat()
        _write_json(_PUB_SCHEDULE_PATH, pub_schedule)

        logger.info(
            "publish_finalize: %s waiting for visuals — notified %s, standup updated",
            episode_code, _PIPELINE_ALERT_EMAIL,
        )
        run_ledger.skipped("waiting for visuals")
        return  # job done (not failed) — resume when Drive watch fires

    logger.info("publish_finalize: visuals present — tile=%s reel=%s", tile_file["name"], reel_file["name"])

    # ── Steps 4–16: Full content production ───────────────────────────────────
    # All work happens in a temp directory, cleaned up in finally. It lives on
    # DISK, not in /tmp — /tmp on the server is a 1.9 GB tmpfs (RAM) and this dir
    # holds the episode audio, WAV clips and rendered MP4s while WhisperX is
    # simultaneously asking for ~1.8 GB. See workspace.py.
    work_dir = workspace.make_work_dir(f"rockstar-{episode_code}-pf-")
    logger.info("publish_finalize: work dir %s", work_dir)

    try:
        _produce_content(
            work_dir=work_dir,
            episode_code=episode_code,
            episode_number=episode_number,
            episode_title=episode_title,
            season_ep_code=season_ep_code,
            slug=slug,
            episode_folder_id=episode_folder_id,
            episode_folder_url=episode_folder_url,
            folder_files=folder_files,
            tile_file=tile_file,
            reel_file=reel_file,
            calendar_event_id=calendar_event_id,
            guest_name=guest_name,
            guest_email=guest_email,
            apple_url=apple_url,
            spotify_url=spotify_url,
            mm_url=mm_url,
            message_id=message_id,
            pub_schedule=pub_schedule,
            trigger=trigger,
            reels_only=reels_only,
        )
    finally:
        shutil.rmtree(work_dir, ignore_errors=True)
        logger.info("publish_finalize: cleaned up %s", work_dir)


# Folders an operator archives old artifacts into, inside an episode folder (e.g.
# "_superseded-2026-07-21", E32's July Round 1). They are HISTORY, not input.
_ARCHIVE_FOLDER_PREFIX = "_superseded"


def _is_archive_folder(f: dict) -> bool:
    return "folder" in f.get("mimeType", "") and f.get("name", "").startswith(_ARCHIVE_FOLDER_PREFIX)


def _gather_files(folder_files: list[dict], list_folder) -> tuple[list[dict], dict]:
    """(extended_files, file_map) for an episode folder: root + immediate subfolders.

    This handles artifacts that ended up in a local/ or transcripts/ subfolder from a
    manual local run or partial earlier pipeline run. Visuals (_find_visual) always use
    root-only folder_files — visuals belong in the root, never in subfolders.

    An ARCHIVE subfolder (`_superseded*`) is skipped. Without that, its files join the
    name → id map, and two things go wrong (E32 re-run, 2026-09): an archived BINARY
    apple_summary.md / quotes.json outranks John's hand-edited Google-Doc copy in the root
    (binaries win pass 1 below, wherever they live), and _drive_replace would DELETE the
    archived faq.md when the root has none.

    file_map resolves two collisions, in priority order:
      1. Google-Docs editor files (mimeType vnd.google-apps.*) are NOT downloadable via
         alt=media — they 403. When a same-named binary exists (e.g. an uploaded
         apple_summary.md that Drive ALSO auto-converted into a Doc), the binary must win.
         This 403 is exactly what crashed the first E28 reprocess (2026-06-16).
      2. Root vs subfolder duplicates — root wins.
    First pass takes binaries only; second pass fills any name that exists solely as a
    Doc (best-effort — still surfaced loudly if undownloadable).
    """
    extended_files = list(folder_files)
    for f in folder_files:
        if "folder" not in f.get("mimeType", ""):
            continue
        if _is_archive_folder(f):
            logger.info("publish_finalize: skipping archive subfolder %r", f["name"])
            continue
        try:
            sub_files = list_folder(f["id"])
            extended_files.extend(sub_files)
            logger.debug("publish_finalize: loaded subfolder %r (%d files)", f["name"], len(sub_files))
        except Exception as exc:
            logger.warning("publish_finalize: could not list subfolder %r: %s", f["name"], exc)

    file_map = {}
    for f in reversed(extended_files):  # root processed last → overrides subfolder dupes
        if "vnd.google-apps" in f.get("mimeType", ""):
            continue
        file_map[f["name"]] = f["id"]
    for f in reversed(extended_files):
        file_map.setdefault(f["name"], f["id"])
    return extended_files, file_map


def _produce_content(
    work_dir: Path,
    episode_code: str,
    episode_number: int,
    episode_title: str,
    season_ep_code: str,
    slug: str,
    episode_folder_id: str,
    episode_folder_url: str,
    folder_files: list[dict],
    tile_file: dict,
    reel_file: dict,
    calendar_event_id: str,
    guest_name: str,
    guest_email: str,
    apple_url: str,
    spotify_url: str,
    mm_url: str,
    message_id: str,
    pub_schedule: dict,
    trigger: str = "gmail",
    reels_only: bool = False,
) -> None:
    """Steps 4–16: download → compose → render → upload → draft → finalize.

    reels_only: run only the reel path (Steps 4, 7a–10.5, and a surgical Step 12
    that replaces reel_*.mp4 in the existing Drive reels folder). Blog, FAQ,
    captions, thank-you draft, and calendar are NOT regenerated — Claude compose
    is non-deterministic, so regenerating would REPLACE existing artifacts with
    different text, not restore them (PP-8: that's a regression, not a rerun).
    """
    # NOTE: the title gate is NOT run here on the schedule title. apple_summary
    # (the human-review surface) wins, so we resolve the final title from it first
    # (see "title source of truth" below) and gate THAT — otherwise a schedule
    # title of "TBD" would hard-fail before the hand-edited summary could rescue it.
    # The gate still runs before any render/upload, just after title resolution.

    # Build file map from root + immediate subfolders.
    # This handles artifacts that ended up in a local/ or transcripts/ subfolder
    # from a manual local run or partial earlier pipeline run.
    # Visuals (_find_visual) always use root-only folder_files — visuals belong
    # in the root, never in subfolders.
    extended_files, file_map = _gather_files(folder_files, drive_client.list_folder)

    # ── Step 4 — Download artifacts from Drive ─────────────────────────────────

    # transcript_fast.txt
    run_ledger.step("4", "download")
    transcript_file = (
        file_map.get("transcript_fast.txt")
        or _find_file_by_pattern(folder_files, r"transcript_fast\.txt$", re.IGNORECASE)
    )
    if not transcript_file:
        raise RuntimeError(f"{episode_code}: transcript_fast.txt not found in Drive folder")
    transcript_path = work_dir / "transcript_fast.txt"
    drive_client.download_file(
        transcript_file if isinstance(transcript_file, str) else transcript_file["id"],
        transcript_path,
    )
    transcript_text = transcript_path.read_text(encoding="utf-8")
    logger.info("publish_finalize: transcript %d chars", len(transcript_text))

    # quotes.json
    quotes_file_id = file_map.get("quotes.json")
    if not quotes_file_id:
        raise RuntimeError(f"{episode_code}: quotes.json not found in Drive folder")
    quotes_path = work_dir / "quotes.json"
    drive_client.download_file(quotes_file_id, quotes_path)
    quotes_data = json.loads(quotes_path.read_text(encoding="utf-8"))
    quotes = quotes_data.get("quotes", [])
    logger.info("publish_finalize: %d quotes loaded", len(quotes))

    # apple_summary.md
    apple_file_id = file_map.get("apple_summary.md")
    if not apple_file_id:
        raise RuntimeError(f"{episode_code}: apple_summary.md not found in Drive folder")
    apple_summary_path = work_dir / "apple_summary.md"
    drive_client.download_file(apple_file_id, apple_summary_path)
    apple_summary_text = apple_summary_path.read_text(encoding="utf-8")

    # ── Guest name: the reviewed summary fills a missing one (2026-10-01) ─────
    # The schedule has no guest name when the form had no answer (E32, E13). Phase 2 then used the placeholder
    # "Guest": the thank-you said "Hi Guest", and the reel gate couldn't tell a host-only episode (E13, Heather
    # and John) from an unnamed guest. apple_summary.md's "About ⟨name⟩" is the human-reviewed name, so it
    # fills the gap: the guest's name for a guest episode, the host's for a solo one (the gate then knows).
    guest_name = _guest_from_summary(guest_name, apple_summary_text, episode_code)

    # ── Title source of truth: apple_summary WINS (ADR-0009) ───────────────────
    # apple_summary.md is the human-review surface — John edits it before the
    # episode goes to the publisher. So its title overrides the Phase-1 schedule
    # title for the reels AND the blog. Falls back to the schedule title only if
    # the summary yields no real title. Then gate the FINAL title we'll render.
    parsed_title = _title_from_apple_summary(apple_summary_text)
    if parsed_title and content_gates.is_real_title(parsed_title):
        if parsed_title != episode_title:
            logger.info(
                "publish_finalize: title from apple_summary overrides schedule: %r (was %r)",
                parsed_title, episode_title,
            )
        episode_title = parsed_title
    else:
        logger.info(
            "publish_finalize: apple_summary has no usable title (%r) — keeping schedule title %r",
            parsed_title, episode_title,
        )
    _assert_real_title(episode_title, episode_code)

    # tile.* and reel.*
    tile_local = work_dir / tile_file["name"]
    # REEL-08: every reel image in the root (one per speaker), the first one keeps the old name `reel_local`.
    reel_locals: dict[str, Path] = {}
    for rf in episode_files.reel_images(folder_files):
        rp = work_dir / rf["name"]
        drive_client.download_file(rf["id"], rp)
        reel_locals[rf["id"]] = rp
    reel_local = work_dir / reel_file["name"]
    drive_client.download_file(tile_file["id"], tile_local)
    drive_client.download_file(reel_file["id"], reel_local)
    logger.info("publish_finalize: downloaded tile=%s reel=%s", tile_local.name, reel_local.name)

    # E{N}-*.m4a audio
    ep_prefix = episode_code.lower() + "-"
    audio_file = None
    for f in folder_files:
        name = f["name"]
        if name.lower().startswith(ep_prefix) and Path(name).suffix.lower() in _AUDIO_EXTENSIONS:
            audio_file = f
            break
    if not audio_file:
        raise RuntimeError(f"{episode_code}: no {episode_code}-*.m4a audio found in Drive folder")
    audio_local = work_dir / audio_file["name"]
    drive_client.download_file(audio_file["id"], audio_local)
    logger.info("publish_finalize: downloaded audio=%s", audio_local.name)

    # ── Step 5 — (retired) ─────────────────────────────────────────────────────
    # The blog URL used to be DERIVED here from the title — a guess, and a wrong guess
    # already shipped once (BLOG-01). It now comes back from Tailor in Step 6 (AC-6).
    blog_post_url = ""

    # ── Step 6 — faq.md + the Tailor blog post (BLOG-02b) ─────────────────────
    run_ledger.step("6", "faq_blog")
    episode_metadata = {
        "episode_number": episode_number,
        "episode_code": episode_code,
        "season_episode_code": season_ep_code,
        "slug": slug,
        "guest_name": guest_name,
        "blog_post_url": blog_post_url,
        "mm_url": mm_url,
    }

    if reels_only:
        logger.info("publish_finalize: reels-only — skipping faq.md + the blog post")
        run_ledger.skipped("reels_only")
    else:
        faq_text = _compose_and_upload_faq(
            work_dir=work_dir,
            transcript_text=transcript_text,
            apple_summary_text=apple_summary_text,
            episode_metadata=episode_metadata,
            file_map=file_map,
            episode_folder_id=episode_folder_id,
        )
        blog_post_url = _write_blog_post(
            work_dir=work_dir,
            episode_code=episode_code,
            episode_number=episode_number,
            episode_title=episode_title,
            apple_summary_text=apple_summary_text,
            quotes=quotes,
            faq_text=faq_text,
            apple_url=apple_url,
            spotify_url=spotify_url,
            tile_local=tile_local,
            tile_file=tile_file,
            file_map=file_map,
            episode_folder_id=episode_folder_id,
        )
        episode_metadata["blog_post_url"] = blog_post_url
        logger.info("publish_finalize: blog_post_url=%s (from the API)", blog_post_url)

    # ── Step 7a — Populate quote timestamps from WhisperX transcript ─────────────
    # Brand Team produces quotes with transcript_start_ms / transcript_end_ms = 0.
    # lookup_quote_timestamps.js fuzzy-matches quote text against segment timestamps
    # and fills them in. Also adds the 'index' and 'topic_slug' fields that
    # extract_quote_clips.sh expects.
    run_ledger.step("7a", "quote_timestamps")
    transcript_json_path = work_dir / "transcript_fast.json"
    transcript_json_file = (
        file_map.get("transcript_fast.json")
        or _find_file_by_pattern(extended_files, r"transcript_fast\.json$", re.IGNORECASE)
    )
    if transcript_json_file:
        drive_client.download_file(
            transcript_json_file if isinstance(transcript_json_file, str) else transcript_json_file["id"],
            transcript_json_path,
        )
        # ── Step 7a-0 — FORCED ALIGNMENT (REEL-05 / ADR 0003, ADR 0004) ──────────
        # lookup runs BEFORE clips are cut, so its only timeline is
        # transcript_fast.json — whose word times are interpolated by even division
        # across each segment. Two consequences, both shipped as defects:
        #   • boundary decisions are made on ±0.5–1s guesses (E28 reel 1's truncated
        #     tail), and
        #   • every inter-word gap is exactly ZERO by construction, so the lead-in
        #     clamp can never prove a silence (lead_in_ms always came out 0) and the
        #     trailing guard's `endMs > guardMs` test can never fire — it was a
        #     structural no-op in production.
        #
        # align_episode.py recovers REAL per-word onsets. It does NOT re-transcribe:
        # WhisperX is expensive Whisper transcription + cheap wav2vec2 forced
        # alignment, and we pay only for the alignment because the text is already
        # known. That is what makes this affordable on a 2-vCPU box.
        #
        # NON-FATAL BY DESIGN, BUT NEVER SILENT: if alignment fails we still publish
        # the episode on interpolated timing (degraded reel framing) rather than
        # stranding it — but we alert and write a standup entry, because a quiet
        # downgrade to the exact timing that caused REEL-05 is the failure mode this
        # whole story exists to remove (PQ-5).
        run_ledger.step("7a-0", "forced_alignment")
        aligned_json_path = work_dir / "transcript_aligned.json"
        venv_python = Path(
            os.environ.get("VENV_PATH", str(_SCRIPTS_DIR / "whisperx_env"))
        ) / "bin" / "python"
        try:
            if not venv_python.is_file():
                raise RuntimeError(f"WhisperX venv python not found at {venv_python}")
            logger.info("publish_finalize: running align_episode (forced alignment)")
            _run_script(
                [
                    str(venv_python), _SCRIPTS_DIR / "align_episode.py", str(work_dir),
                    "--in", str(transcript_json_path),
                    "--out", str(aligned_json_path),
                ],
                work_dir,
                "align_episode",
            )
            if not aligned_json_path.is_file():
                raise RuntimeError("align_episode reported success but wrote no output")
        except Exception as exc:  # noqa: BLE001 — degraded path must stay loud
            logger.error("publish_finalize: forced alignment FAILED — %s", exc)
            _prepend_standup(
                episode_code,
                f"⚠️ Forced alignment failed ({exc}). Reels for this episode were "
                f"framed on INTERPOLATED timing — expect ADR 0003 boundary drift "
                f"(truncated or trailing clip ends) and no ADR 0004 excision. "
                f"Re-run with alignment before publishing the reels.",
            )
            try:
                gmail_client.send_pipeline_alert(
                    to=_PIPELINE_ALERT_EMAIL,
                    subject=f"{episode_code}: forced alignment failed — reels on degraded timing",
                    body=(
                        f"align_episode.py failed for {episode_code}: {exc}\n\n"
                        f"The episode will still publish, but reel clip boundaries fall back "
                        f"to interpolated segment timing (the REEL-05 defect class). "
                        f"Review the reels before they go out."
                    ),
                )
            except Exception:  # noqa: BLE001 — an alert failure must not strand the job
                logger.exception("publish_finalize: could not send alignment-failure alert")
            aligned_json_path = None

        logger.info("publish_finalize: running lookup_quote_timestamps")
        lookup_cmd = [
            "node", _SCRIPTS_DIR / "lookup_quote_timestamps.js",
            "--quotes", str(quotes_path),
            "--transcript", str(transcript_json_path),
        ]
        if aligned_json_path is not None:
            lookup_cmd += ["--aligned", str(aligned_json_path)]
        _run_script(lookup_cmd, work_dir, "lookup_quote_timestamps")
        # Reload quotes after timestamp injection
        quotes_data = json.loads(quotes_path.read_text(encoding="utf-8"))
        quotes = quotes_data.get("quotes", [])
        logger.info("publish_finalize: timestamps populated for %d quotes", len(quotes))
    else:
        logger.warning(
            "publish_finalize: transcript_fast.json not found — skipping timestamp lookup "
            "(extract_quote_clips will warn on 0-timestamp quotes)"
        )
        run_ledger.skipped("transcript_fast.json not found")

    # ── Step 7 — Extract quote audio clips ─────────────────────────────────────
    run_ledger.step("7", "extract_clips")
    logger.info("publish_finalize: extracting quote clips")
    # Script interface: extract_quote_clips.sh <episode_folder> <audio_filename>
    # We use work_dir as the episode_folder since all artifacts are there.
    _run_script(
        ["bash", _SCRIPTS_DIR / "extract_quote_clips.sh", work_dir, audio_file["name"]],
        work_dir,
        "extract_quote_clips",
    )
    clips_dir = work_dir / "clips"
    clips_manifest = clips_dir / "clips_manifest.json"
    if not clips_manifest.exists():
        raise RuntimeError(
            f"{episode_code}: extract_quote_clips.sh did not produce clips/clips_manifest.json"
        )
    logger.info("publish_finalize: clips extracted — manifest at %s", clips_manifest)

    # ── Step 8 — Transcribe clips for word timestamps ──────────────────────────
    run_ledger.step("8", "transcribe_clips")
    logger.info("publish_finalize: transcribing clips (whisperx large-v3)")
    # Script interface: transcribe_clips.sh <episode_folder>
    _run_script(
        ["bash", _SCRIPTS_DIR / "transcribe_clips.sh", work_dir],
        work_dir,
        "transcribe_clips",
    )
