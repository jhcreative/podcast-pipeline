def _ty_fingerprint(state: dict) -> str:
    """sha256 of the draft as Gmail stores it: To, Subject and the decoded plain body. Taken from
    what Gmail RETURNS, never from what we sent, so Gmail's normalisation can't look like an edit."""
    blob = f"{state['to']}\n{state['subject']}\n{state['body']}"
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def _update_schedule_entry(episode_number: int, **fields) -> None:
    """Read-modify-write ONE episode's fields in the schedule (never a whole-blob replace)."""
    sched = _read_json(_PUB_SCHEDULE_PATH)
    for ep in sched.get("episodes", []):
        if ep.get("episode_number") == episode_number and ep.get("drive_folder_id"):
            ep.update(fields)
            sched["updated_at"] = datetime.now(timezone.utc).isoformat()
            _write_json(_PUB_SCHEDULE_PATH, sched)
            return
    logger.warning("publish_finalize: E%s not in the schedule — %s not recorded", episode_number, sorted(fields))


def _record_ty_draft(episode_number: int, draft: dict) -> None:
    """Record {draft_id, message_id, sha256} for a thank-you draft we just created. Never fails the
    job: without a record, a later links-only run leaves the draft alone and says so (safe)."""
    try:
        state = gmail_client.draft_state(draft["id"])
        _update_schedule_entry(
            episode_number,
            ty_draft={
                "draft_id": draft["id"],
                "message_id": state["message_id"],
                "sha256": _ty_fingerprint(state),
                "single_text_plain": state["single_text_plain"],
                "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            },
        )
    except Exception as exc:  # noqa: BLE001 — see docstring
        logger.warning(
            "publish_finalize: E%s thank-you draft not fingerprinted (%s: %s) — a late "
            "publisher email will leave it alone",
            episode_number,
            type(exc).__name__,
            exc,
        )
        run_ledger.anomaly("thank-you not fingerprinted")


def _swap_ty_draft(ep_entry: dict, episode_number: int, apple_url: str, spotify_url: str) -> str:
    """Put the episode links into OUR thank-you draft, in place, only if no person has touched it.
    Returns one line for the alert."""
    rec = ep_entry.get("ty_draft")
    if not rec:
        return "Thank-you: no fingerprint of the draft (made before TRIG-03) — left alone. Paste the links by hand."
    try:
        state = gmail_client.draft_state(rec["draft_id"])
    except gmail_client.DraftGone:
        return (
            "Thank-you: the draft is gone (sent or deleted) — nothing created, nothing sent. If it went "
            "with the show links, follow up by hand."
        )
    ty = thank_you.build_draft(
        guest_name=ep_entry.get("guest_name") or "Guest",
        episode_title=ep_entry.get("episode_title", "TBD"),
        apple_url=apple_url,
        spotify_url=spotify_url,
        blog_url=ep_entry.get("blog_post_url") or "",
        guest_email=ep_entry.get("guest_email") or "",
    )
    _assert_thank_you_wellformed(ty["body"])
    target = {"to": ty["to"], "subject": ty["subject"], "body": ty["body"].rstrip("\n")}
    if state["single_text_plain"] and _ty_fingerprint({**state, "body": state["body"].rstrip("\n")}) == _ty_fingerprint(
        target
    ):
        # A retry after an update that succeeded (its read-back or the record write failed): the draft
        # already says exactly what we would write. It is ours; record it, don't call it a hand edit.
        _update_schedule_entry(
            episode_number, ty_draft={**rec, "message_id": state["message_id"], "sha256": _ty_fingerprint(state)}
        )
        return "Thank-you: the draft already carries the episode links."
    untouched = (
        state["message_id"] == rec["message_id"]
        and state["single_text_plain"]
        and _ty_fingerprint(state) == rec["sha256"]
    )
    if not untouched:
        return "Thank-you: the draft was edited by a person — left alone. Paste the links by hand."
    moved = state["to"] != ty["to"]
    gmail_client.update_draft(rec["draft_id"], ty["to"], ty["subject"], ty["body"])
    # Record what Gmail now holds AT ONCE: a retry then finds the draft still ours, not "edited".
    new = gmail_client.draft_state(rec["draft_id"])
    _update_schedule_entry(
        episode_number,
        ty_draft={
            **rec,
            "message_id": new["message_id"],
            "sha256": _ty_fingerprint(new),
            "single_text_plain": new["single_text_plain"],
            "links_swapped_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        },
    )
    return "Thank-you: the draft now carries the episode links (updated in place, still a draft, not sent)." + (
        f" Its recipient changed from {state['to']!r} to {ty['to']!r} (the schedule's guest email)." if moved else ""
    )


def _links_only(
    *,
    ep_entry: dict,
    episode_code: str,
    episode_number: int,
    apple_url: str,
    spotify_url: str,
    mm_url: str,
    message_id: str,
    subject: str,
    body_text: str,
) -> None:
    """TRIG-03: the episode's real links arrived after Phase 2 ran on the show pages. Swap them in
    where the pipeline put a placeholder — the blog draft's listen buttons and our untouched
    thank-you draft — record them, and send ONE alert. No model call, no reel, no caption, no FAQ.
    Every refusal writes nothing and names the manual step instead."""
    # AC-12 (John, 2026-10-10, from the real emails): the EP number is not proof on its own. The email must
    # carry at least _MIN_TITLE_WORDS of THIS episode's distinctive title words, and no other episode may score
    # as high. Real data: E33's email had 3 of 8 (a reworded title, no guest name), E32's 5 of 6.
    sched = _read_json(_PUB_SCHEDULE_PATH).get("episodes", [])
    mine, need = _title_score(ep_entry, subject, body_text)
    if mine < need:
        _alert(
            f"{episode_code}: publisher email doesn't name the episode — nothing written",
            f"The email was matched to {episode_code} by its EP number, but only {mine} of the {need} title "
            f"words needed from {ep_entry.get('episode_title')!r} are in it "
            f"(found: {', '.join(_title_hits(ep_entry, subject, body_text)) or 'none'}). "
            f"Nothing was changed. Check the "
            f"email and paste the links by hand:\n  Apple:   {apple_url}\n  Spotify: {spotify_url}\n",
        )
        return
    rivals = [
        e for e in sched if e.get("episode_number") != episode_number and _title_score(e, subject, body_text)[0] >= mine
    ]
    if rivals:
        _alert(
            f"{episode_code}: publisher email names two episodes — nothing written",
            f"The email was matched to {episode_code} ({', '.join(_title_hits(ep_entry, subject, body_text))}), but "
            + "; ".join(f"{e.get('episode_code')} ({', '.join(_title_hits(e, subject, body_text))})" for e in rivals)
            + " match as well or better. Nothing was "
            "changed. Check the email and paste the links by hand.\n",
        )
        return

    # AC-11: only this show's episode links, and none another episode already holds.
    spotify_url = publisher_email.clean_spotify_url(spotify_url)
    problems = publisher_email.episode_url_problems(apple_url, spotify_url)
    ids = publisher_email.episode_ids(apple_url, spotify_url)
    for e in sched:
        if e.get("episode_number") == episode_number:
            continue
        other = publisher_email.episode_ids(e.get("apple_url") or "", e.get("spotify_url") or "")
        for kind, mine, theirs in (("Apple", ids[0], other[0]), ("Spotify", ids[1], other[1])):
            if mine and mine == theirs:
                problems.append(f"{kind} episode id {mine} already belongs to {e.get('episode_code')}")
    if problems:
        _alert(
            f"{episode_code}: publisher email links refused — nothing written",
            "The late publisher email's links did not pass the check, so nothing was changed:\n\n"
            + "\n".join(f"  • {p}" for p in problems)
            + "\n",
        )
        return

    lines, manual = [], False
    # Blog: listen buttons that still point at a show page, and nothing else.
    try:
        r = blog_publish.swap_listen_links(
            episode_code=episode_code,
            mapping={_SHOW_APPLE_URL: apple_url, _SHOW_SPOTIFY_URL: spotify_url},
            api_base=_BLOG_API_BASE,
            public_base=_BLOG_BASE_URL,
            credentials=blog_publish.load_credentials(),
            record_path=_BLOG_RECORD_PATH,
            lock_path=_BLOG_LOCK_PATH,
        )
        if r.outcome == "swapped":
            lines.append(
                f"Blog draft {r.url}: {r.swapped} listen button(s) now point at the episode."
                + ("" if r.restamped else " (The draft had hand edits; they are untouched.)")
            )
        else:
            manual = manual or r.outcome != "nothing_to_swap"
            lines.append(
                f"Blog {r.url}: not changed — {r.reason}."
                + (" Paste the links by hand." if r.outcome != "nothing_to_swap" else "")
            )
    except blog_publish.BlogStop as exc:
        manual = True
        lines.append(f"Blog: not changed — {exc}")
        run_ledger.anomaly("blog links not swapped")

    # Thank-you: our draft, in place, only if untouched.
    if _guest_is_host(ep_entry.get("guest_name") or ""):
        lines.append("Thank-you: none (Heather is the guest).")
    else:
        line = _swap_ty_draft(ep_entry, episode_number, apple_url, spotify_url)
        manual = manual or "by hand" in line
        lines.append(line)

    lines.append(
        "Reels, captions, cards, FAQ, show notes, and the thank_you.md copy in Drive: not touched. "
        "Where one quotes a show link, it still does."
    )
    # The schedule is written LAST, so a retry after a partial run re-reaches the same end state.
    sched_ep = next(
        (e for e in _read_json(_PUB_SCHEDULE_PATH).get("episodes", []) if e.get("episode_number") == episode_number), {}
    )
    _update_schedule_entry(
        episode_number,
        apple_url=apple_url,
        spotify_url=spotify_url,
        mm_url=mm_url or sched_ep.get("mm_url"),
        mission_matters_email_id=message_id or sched_ep.get("mission_matters_email_id"),
        episode_links_pending=manual,
        notes=(sched_ep.get("notes") or "")
        + f" | links in {datetime.now(timezone.utc).date().isoformat()}"
        + (" (manual steps left)" if manual else ""),
    )
    _alert(
        f"{episode_code}: real episode links in" + (" — some by hand" if manual else ""),
        f"The publisher's email for {episode_code} arrived after Phase 2 "
        f"(matched on: {', '.join(_title_hits(ep_entry, subject, body_text))}). Links:\n"
        f"  Apple:   {apple_url}\n  Spotify: {spotify_url}\n\n" + "\n".join(lines) + "\n",
    )
    _prepend_standup(episode_code, "[LINKS] " + " | ".join(lines))
    logger.info("publish_finalize: %s links-only done (manual steps: %s)", episode_code, manual)


# Words every publisher email carries, whatever the episode: the show's own name and the email's own words.
# They prove nothing about WHICH episode, so they never count.
_TITLE_NOISE = {
    "genx",
    "menopause",
    "episode",
    "podcast",
    "listen",
    "spotify",
    "apple",
    "heather",
    "reilly",
    "hiemstra",
    "rockstar",
    "blends",
    "about",
    "their",
    "there",
    "where",
    "which",
}
_MIN_TITLE_WORDS = 3


def _title_words(title: str) -> set[str]:
    """The title's distinctive words: over 4 letters, not noise."""
    return {
        w for w in re.sub(r"[^a-z0-9]+", " ", (title or "").lower()).split() if len(w) > 4 and w not in _TITLE_NOISE
    }


def _title_hits(ep: dict, subject: str, body: str) -> list[str]:
    """The episode's distinctive title words that the email carries, sorted — named in every AC-12 alert."""
    text = set(re.sub(r"[^a-z0-9]+", " ", f"{subject} {body}".lower()).split())
    return sorted(_title_words(ep.get("episode_title") or "") & text)


def _title_score(ep: dict, subject: str, body: str) -> tuple[int, int]:
    """(distinctive title words found in the email, words needed): need is _MIN_TITLE_WORDS, or every word
    when the title has fewer. A title with no distinctive word can never be matched (need 1, found 0)."""
    words = _title_words(ep.get("episode_title") or "")
    text = set(re.sub(r"[^a-z0-9]+", " ", f"{subject} {body}".lower()).split())
    return len(words & text), max(1, min(_MIN_TITLE_WORDS, len(words)))


