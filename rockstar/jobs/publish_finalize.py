def _assign_reel_backgrounds(
    quotes_path: Path,
    folder_files: list[dict],
    reel_locals: dict,
    episode_code: str,
    all_speakers: list[str] | None = None,
    named: bool = False,
) -> None:
    """REEL-08: write `background_path` onto every reel quote from episode_files.background_for. A quote with
    no usable image (several speakers, one image, no name match) stops Phase 2 BEFORE rendering, with the exact
    file to drop: a reel showing the wrong person is worse than a held one. Host quotes with no image of their
    own keep render_reel's BrandAssets host background."""
    data = json.loads(quotes_path.read_text(encoding="utf-8"))
    reels = episode_files.reel_images(folder_files)
    # Every speaker in the episode (QUOTE-03 passes them when quotes.json holds only the named ones), so rule 3's
    # "one image, one other speaker" can't hand a co-guest's photo to a subset's quote.
    speakers = all_speakers if all_speakers is not None else [q.get("speaker") or "" for q in data.get("quotes", [])]
    problems = []
    for q in data.get("quotes", []):
        if (
            q.get("reel_candidate") is False and not named
        ):  # a named quote renders (--reel NN), so it gets its own image
            continue
        f, rule = episode_files.background_for(q.get("speaker") or "", reels, speakers)
        if f is not None:
            q["background_path"] = str(reel_locals[f["id"]])
            q["background_rule"] = rule
        elif rule == "host-default":
            q.pop("background_path", None)
            q["background_rule"] = rule
        else:
            problems.append(f"{q.get('id', '?')}: {rule}")
    if problems:
        raise content_gates.GateFailure(
            f"{episode_code}: reel backgrounds don't match the speakers. " + "; ".join(sorted(set(problems)))
        )
    quotes_path.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    logger.info(
        "publish_finalize: reel backgrounds by speaker: %s",
        {q.get("id"): q.get("background_rule") for q in data.get("quotes", []) if q.get("background_rule")},
    )


