def _record_cards_status(cards_status) -> None:
    """Step 12b's outcome. card_step alerts and carries on (CARD-05), so a failure comes back as a status, not an
    exception: E6's 12b closed "ok" with no cards built (OBS-02)."""
    if str(cards_status).startswith("skipped"):
        run_ledger.skipped("cards/ not empty")
    elif str(cards_status).startswith("failed"):
        run_ledger.anomaly(_card_failure_reason(cards_status))


def _card_failure_reason(cards_status: str) -> str:
    """card_step's "failed: the render stage failed" → "cards not built: render"; anything else → "cards not built".
    Only card_step's own stage names pass through, so the reason is always a fixed string from our code."""
    m = re.match(r"failed: the (.+?) stage failed$", str(cards_status))
    return f"cards not built: {m.group(1)}" if m and m.group(1) in card_step.TIMEOUTS else "cards not built"


def _write_blog_post(
    work_dir: Path,
    episode_code: str,
    episode_number: int,
    episode_title: str,
    apple_summary_text: str,
    quotes: list,
    faq_text: str,
    apple_url: str,
    spotify_url: str,
    tile_local: Path | None,
    tile_file: dict | None,
    file_map: dict,
    episode_folder_id: str,
) -> str:
    """Step 6b — the episode's blog post, as a Tailor DRAFT (BLOG-02b). Returns its URL.

    build (no model) → gate → blog_post.json to Drive → blog_publish.publish. The URL
    returned is _BLOG_BASE_URL + the slug Tailor returned (AC-6), so a wrong guess can no
    longer reach the schedule, the captions or the guest's thank-you (BLOG-01).

    Failure policy — each branch alerts John, and none leaves a half-written post:
      • gate / build refusal (AC-3): alert, NO Tailor call, PermanentFailure. Phase 2 stops
        here, before reels and the thank-you, because there is no URL to give them.
      • BlogStop (slug collision, a recorded post gone, wrong role, refused login, 429):
        alert, PermanentFailure — a retry would get the same answer.
      • a PUBLISHED post: alert, SKIP the write, and carry on with its real URL (AC-5).
      • an outage (network / 5xx) or a busy lock: raised as-is; the worker retries, and the
        record makes the retry update the same draft (AC-5).
    """
    meta = {
        "episode_title": episode_title,
        "episode_number": episode_number,
        "spotify_url": spotify_url,
        "apple_url": apple_url,
    }
    try:
        post = blog_post.build_post(apple_summary_text, quotes, faq_text, meta)
        content_gates.assert_blog_post_wellformed(post, quotes, episode_code)
    except content_gates.GateFailure as exc:
        _alert(
            f"{episode_code}: blog post refused before any write — Phase 2 stopped",
            f"The blog post did not pass its gate, so nothing was written to the site and "
            f"Phase 2 stopped before reels and the thank-you draft.\n\n  {exc}\n\n"
            f"Fix the input (apple_summary / quotes.json / faq.md) and re-run "
            f"venv/bin/python -m rockstar.tools.reprocess_episode --episode {episode_number}.\n",
        )
        raise PermanentFailure(str(exc)) from exc

    # AC-9 — the built post is the review surface and the audit trail on Drive. The post
    # only: no credential, no response, no cookie (C-4). An old blog_page.html is left in
    # place as history; nothing reads it any more.
    post_path = work_dir / "blog_post.json"
    post_path.write_text(json.dumps(post, indent=2, ensure_ascii=False), encoding="utf-8")
    _drive_replace(file_map, "blog_post.json", post_path, episode_folder_id, "application/json")

    try:
        result = blog_publish.publish(
            post,
            quotes,
            episode_code=episode_code,
            api_base=_BLOG_API_BASE,
            public_base=_BLOG_BASE_URL,
            credentials=blog_publish.load_credentials(),
            record_path=_BLOG_RECORD_PATH,
            lock_path=_BLOG_LOCK_PATH,
            tile_path=tile_local,
        )
    except (blog_publish.BlogStop, content_gates.GateFailure) as exc:
        _alert(
            f"{episode_code}: blog post NOT written — Phase 2 stopped",
            f"{exc}\n\nNothing was published. Phase 2 stopped before reels and the thank-you "
            f"draft, because it has no post URL to give them. Resolve it, then re-run "
            f"venv/bin/python -m rockstar.tools.reprocess_episode --episode {episode_number}.\n",
        )
        raise PermanentFailure(str(exc)) from exc

    tile_link = f"https://drive.google.com/file/d/{tile_file['id']}/view" if tile_file else None
    subject, body = blog_publish.draft_alert(
        result, episode_code, tile_link=tile_link, source=blog_publish.credential_source()
    )
    _alert(subject, body)
    logger.info(
        "publish_finalize: blog %s — %s (status=%s, cover=%s)",
        result.outcome,
        result.url,
        result.status,
        result.cover_mode,
    )
    return result.url


def _thank_you_ready_alert(episode_code: str, to: str, subject: str, blog_post_url: str) -> None:
    """Step 13's report (OPEN-1, John 2026-09-22): the thank-you draft exists either way, but it
    is called READY only when the blog post answers 200. On a normal run it won't — the post
    was just created as a draft — so the subject names it: "blog post not published yet"."""
    blog_live, blog_check = blog_publish.post_live_check(blog_post_url)
    logger.info("publish_finalize: thank-you blog check — %s", blog_check)
    _alert(
        f"{episode_code}: thank-you draft ready" + ("" if blog_live else " — blog post not published yet"),
        f"The guest thank-you draft is in Gmail (DRAFT — never sent).\n  To: {to}\n"
        f"  Subject: {subject}\n\n{blog_check}\n",
    )


