def _select_quotes(quotes_path: Path, ids: list[str], episode_code: str) -> list[dict]:
    """QUOTE-03: keep only the named quotes in the work copy of quotes.json (every other key kept). An id that isn't in
    the episode is a PermanentFailure: a typo must not quietly re-render nothing."""
    data = json.loads(quotes_path.read_text(encoding="utf-8"))
    have = {q.get("id") for q in data.get("quotes", [])}
    missing = [i for i in ids if i not in have]
    if missing:
        raise PermanentFailure(
            f"{episode_code}: no quote {', '.join(missing)} in quotes.json (has {', '.join(sorted(map(str, have)))})"
        )
    data["quotes"] = [q for q in data["quotes"] if q.get("id") in ids]
    for q in data["quotes"]:
        # render_reel.js and extract_quote_clips.sh key on index; without 7a's lookup it would fall back to list
        # position.
        q.setdefault("index", int(str(q["id"]).lstrip("q")))
    quotes_path.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    logger.info("publish_finalize: reels for %s only", ", ".join(ids))
    return data["quotes"]


def _stale_captions(files: list[dict], numbers: list[str]) -> list[str]:
    """Caption files in reels/ for a re-rendered reel number. Step 11 writes reel_NN_captions.md, one per reel; a
    per-quote run keeps it, and its text predates the correction, so it is stale whatever the reel's new name.
    (QUOTE-03 P1 quarantines them; P4 writes new ones.)"""
    pattern = rf"^reel_({'|'.join(map(re.escape, numbers))})_.*\.(md|txt)$"
    return sorted(f["name"] for f in files if numbers and re.match(pattern, f["name"], re.IGNORECASE))


def _flag_stale_captions(files: list[dict], numbers: list[str], episode_code: str) -> None:
    stale = _stale_captions(files, numbers)
    if stale:
        logger.warning("publish_finalize: %s stale caption file(s) left in reels/: %s", episode_code, stale)
        _prepend_standup(
            episode_code,
            f"⚠️ Reels re-rendered for corrected quotes; {len(stale)} caption file(s) in "
            f"reels/ were written for the old reels and may quote the corrected line: "
            f"{', '.join(stale)}. Don't post them (QUOTE-03 P1/P4).",
        )
        run_ledger.anomaly("stale captions left in reels/")


def _reel_numbers(quotes: list[dict]) -> list[str]:
    """The two-digit reel numbers of these quotes, as render_reel.js names them (reel_NN_<slug>.mp4)."""
    return [str(q.get("index") or int(str(q["id"]).lstrip("q"))).zfill(2) for q in quotes]


def _reels_to_replace(files: list[dict], numbers: list[str] | None) -> list[dict]:
    """The reel mp4s a reels-only run replaces: every reel_*.mp4, or with named quotes only reel_NN_*.mp4 for their
    numbers, whatever the old slug (a restored quote can get a new one). Captions and other files are never in it."""
    pattern = r"^reel_.*\.mp4$" if numbers is None else rf"^reel_({'|'.join(map(re.escape, numbers))})_.*\.mp4$"
    return [f for f in files if re.match(pattern, f["name"], re.IGNORECASE)]


def _rerun_command(
    episode_number: int,
    apple_url: str,
    spotify_url: str,
    mm_url: str,
    reels_only: bool,
    only_quotes: list[str] | None = None,
) -> str:
    """The box command that re-runs this Phase 2 as it was asked: the same mode, the same links (Toby, REEL-11).

    The links come from an external email, so each is shell-quoted: John pastes this line into a shell. A reels-only
    run re-runs reels only, because a full reprocess would recompose the FAQ, blog and thank-you (PP-8)."""
    args = ["venv/bin/python", "-m", "rockstar.tools.reprocess_episode", "--episode", str(episode_number)]
    missing = []
    if reels_only:
        args.append("--reels-only")
        if only_quotes:
            args += ["--quotes", ",".join(only_quotes)]  # the same reels, not every reel in the episode
    else:
        for flag, url in (("--apple", apple_url), ("--spotify", spotify_url)):
            args += [flag, url or f"<{flag[2:]}-url>"]
            missing += [] if url else [flag]
        if mm_url:
            args += ["--mm", mm_url]
    # .env first, as reprocess_episode.py's own docstring says: it can set DB_PATH.
    cmd = "cd /opt/rockstar-pipeline && set -a && source .env && set +a && " + " ".join(
        a if a.startswith("<") else shlex.quote(a) for a in args
    )
    # A full run needs both links, and the tool refuses an empty one: name what to fill in, never print a dead command.
    return cmd + (f"   (fill in {' and '.join(missing)} first)" if missing else "")


def _force_align(
    work_dir: Path, episode_code: str, transcript_json_path: Path, *, rerun: str, reels_only: bool = False
) -> Path:
    """Step 7a-0: real per-word onsets from align_episode.py (REEL-05 / ADR 0003, ADR 0004). Returns the aligned
    transcript, or stops Phase 2 (REEL-11).

    On failure: one standup line, one alert with the cause and the re-run command, then PermanentFailure. Nothing
    after 7a-0 runs: no clips, reels, cards or thank-you. In a full run the FAQ and the blog draft (step 6) are
    already written and stay as drafts; the alert says so. An OOM is the same stop, and _run_script has already
    alerted for it (CLIP-01a).
    """
    aligned = work_dir / "transcript_aligned.json"
    venv_python = config.whisperx_venv() / "bin" / "python"
    try:
        if not venv_python.is_file():
            raise RuntimeError(f"WhisperX venv python not found at {venv_python}")
        logger.info("publish_finalize: running align_episode (forced alignment)")
        _run_script(
            [
                str(venv_python),
                _SCRIPTS_DIR / "align_episode.py",
                str(work_dir),
                "--in",
                str(transcript_json_path),
                "--out",
                str(aligned),
            ],
            work_dir,
            "align_episode",
        )
        if not aligned.is_file():
            raise RuntimeError("align_episode reported success but wrote no output")
    except PermanentFailure:
        raise  # an OOM: _run_script alerted once already (CLIP-01a)
    except Exception as exc:  # noqa: BLE001 — every other failure is the REEL-11 stop below
        cause = getattr(exc, "stderr_tail", "") or str(exc)
        logger.error("publish_finalize: forced alignment FAILED — %s", exc)
        done = "" if reels_only else "Already done, and kept as drafts: the FAQ and the blog draft (step 6).\n\n"
        _prepend_standup(
            episode_code,
            f"⛔ Forced alignment failed — Phase 2 stopped, no reels made ({exc}). "
            + ("" if reels_only else "The FAQ and blog draft are written. ")
            + f"Re-run: {rerun}",
        )
        _alert(
            f"{episode_code}: forced alignment failed — Phase 2 stopped, no reels made",
            f"align_episode.py failed for {episode_code}, so Phase 2 stopped at step 7a-0. No clips, reels, cards "
            f"or thank-you draft were made: reels framed on guessed timing are the REEL-05 defects (REEL-11).\n\n"
            f"{done}"
            f"Cause (the end of the script's output):\n{cause}\n\n"
            f"Fix the cause, then re-run on the box:\n  {rerun}\n",
        )
        raise PermanentFailure(f"forced alignment failed: {exc}") from exc
    return aligned


