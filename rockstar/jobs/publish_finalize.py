def _drive_delete_all_by_name(files: list[dict], name: str) -> int:
    """Delete all Drive items (files or folders) matching name. Returns count deleted."""
    from googleapiclient.discovery import build as _build

    from rockstar.clients.google_auth import drive_credentials as _drive_creds

    svc = _build("drive", "v3", credentials=_drive_creds(), cache_discovery=False)
    deleted = 0
    for f in files:
        if f["name"] == name:
            try:
                svc.files().delete(fileId=f["id"]).execute()
                deleted += 1
            except Exception as exc:
                logger.warning("publish_finalize: could not delete %r (%s): %s", name, f["id"], exc)
                run_ledger.anomaly("Drive file not deleted")
    return deleted


# ── main entry point ────────────────────────────────────────────────────────────


def run(job_id: int, episode_id: str, payload: dict) -> None:
    """
    PUBLISH_FINALIZE — Legacy Publisher live email → full content production.

    payload (gmail trigger):
      {"trigger": "gmail", "message_id": "...", "thread_id": "...",
       "subject": "...", "sender": "..."}

    payload (drive_resume trigger — visuals just added):
      {"trigger": "drive_resume", "apple_url": "...", "spotify_url": "...",
       "mm_url": "...", "episode_number": 26, "message_id": "..."}
    """
    logger.info("publish_finalize start — job_id=%d payload=%s", job_id, payload)
    try:
        _run_pipeline(job_id, payload)
    except PermanentFailure:
        raise  # already logged; worker stops retries
    except content_gates.GateFailure as exc:
        # A content gate said no (guest not featured, reel backgrounds don't match the speakers, …). Retrying
        # can't change the answer: it used to be retried 5× silently, recomposing the FAQ each time, with no
        # word to John. Tell him once, with the gate's own reason, and stop. Fix the input, then re-touch an image.
        ep = payload.get("episode_number")
        _alert(f"E{ep if ep is not None else '?'}: Phase 2 stopped — fix and re-drop an image", f"{exc}\n")
        raise PermanentFailure(f"gate: {exc}") from exc
    except Exception as exc:
        logger.exception("publish_finalize: unhandled error: %s", exc)
        raise  # worker retries with exponential back-off


def _run_pipeline(job_id: int, payload: dict) -> None:
    """Inner pipeline. Called by run(); errors propagate up."""
    trigger = payload.get("trigger", "gmail")
    from_email = False

    # reels_only: re-render + replace reel mp4s, touch nothing else.
    # Only the reprocess trigger sets it (see rockstar/tools/reprocess_episode.py --reels-only).
    reels_only = bool(payload.get("reels_only"))
    # QUOTE-03: a reels-only run may name its quotes; only their reels are re-rendered and replaced.
    only_quotes = list(payload.get("quotes") or [])
    if only_quotes and not reels_only:
        raise PermanentFailure("PUBLISH_FINALIZE: 'quotes' is only for a reels_only reprocess")
    # cards_only: rebuild the quote-card set on the box and nothing else (John, 2026-10-13: no manual fallback; the
    # Mac path, scripts/new-cards.sh, broke on the OVH box). Like reels_only, only the reprocess trigger sets it.
    cards_only = bool(payload.get("cards_only"))
    if cards_only and reels_only:
        raise PermanentFailure("PUBLISH_FINALIZE: cards_only and reels_only are separate runs")

    # ── Step 1 — Parse MM email (or read from resume payload) ──────────────────
    run_ledger.step("1", "parse_email")
    if trigger == "reprocess":
        apple_url = payload.get("apple_url", "")
        spotify_url = payload.get("spotify_url", "")
        mm_url = payload.get("mm_url", "")
        episode_number = int(payload["episode_number"])
        message_id = ""
        if not (reels_only or cards_only) and not (apple_url and spotify_url):
            raise PermanentFailure(
                "PUBLISH_FINALIZE reprocess: apple_url and spotify_url are required "
                "unless reels_only or cards_only is set (they feed the blog/captions compose steps)"
            )
        logger.info(
            "publish_finalize: reprocess path — E%d apple=%s spotify=%s reels_only=%s",
            episode_number,
            apple_url,
            spotify_url,
            reels_only,
        )
    elif trigger == "visuals":
        # TRIG-02: the images arrived. Links are whatever the operator passed (none, normally) → show pages.
        apple_url = payload.get("apple_url") or _SHOW_APPLE_URL
        spotify_url = payload.get("spotify_url") or _SHOW_SPOTIFY_URL
        mm_url = payload.get("mm_url", "")
        episode_number = int(payload["episode_number"])
        message_id = ""
        logger.info(
            "publish_finalize: visuals path — E%d (episode links %s)",
            episode_number,
            "pending: show pages used" if _links_pending(apple_url, spotify_url) else "given",
        )
    elif trigger in ("drive_resume", "drive_changes_resume"):
        # drive_changes has always enqueued "drive_changes_resume"; only "drive_resume" was recognised, so a
        # resume fell into the e-mail branch below. Both names land here now.
        apple_url = payload["apple_url"]
        spotify_url = payload["spotify_url"]
        mm_url = payload.get("mm_url", "")
        episode_number = int(payload["episode_number"])
        message_id = payload.get("message_id", "")
        logger.info(
            "publish_finalize: drive_resume path — E%d apple=%s spotify=%s",
            episode_number,
            apple_url,
            spotify_url,
        )
    else:
        # Gmail trigger — parse the publisher "Episode is Live" email.
        # All assumptions about the (drifting) publisher contract — sender
        # allowlist, reply guard, HTML-only body, mangled Apple ids, missing EP
        # number — live in rockstar/clients/publisher_email.py. See that module's header.
        from_email = True  # TRIG-03: route on how this job started, not on the trigger's name (Toby F-5)
        message_id = payload.get("message_id", "")
        if not message_id:
            raise PermanentFailure("PUBLISH_FINALIZE payload missing message_id")

        msg = gmail_client.get_message(message_id)
        sender = gmail_client.get_header(msg, "from")
        subject = gmail_client.get_header(msg, "subject")
        in_reply_to = gmail_client.get_header(msg, "in-reply-to")

        # TRIG-03 AC-10: the From line proves nothing on its own (Legacy Publisher publishes DMARC
        # p=NONE, so a forged From is delivered). Google's verdict decides, checked here as well as in
        # the webhook, because a job can be retried or enqueued by hand.
        authentic, why = publisher_email.authenticated_sender(msg.get("payload", {}).get("headers", []))
        if not authentic:
            raise PermanentFailure(f"PUBLISH_FINALIZE: sender {sender!r} not authenticated: {why}")
        if not publisher_email.is_publish_notification(subject, in_reply_to=in_reply_to):
            raise PermanentFailure(
                f"PUBLISH_FINALIZE: {subject!r} is not an original publish notification "
                f"(reply/forward, or missing 'episode is live')"
            )

        # Body is now HTML-only — read text AND html so the listen links resolve.
        text_body = gmail_client.extract_plain_text(msg)
        html_body = gmail_client.extract_html(msg)
        urls = publisher_email.extract_publish_urls(text_body, html_body)
        apple_url, spotify_url, mm_url = urls["apple_url"], urls["spotify_url"], urls["mm_url"]

        # Identify the episode WITHOUT requiring an EP number (title match, then
        # single-awaiting-publish fallback). None ⇒ ambiguous ⇒ fail safe.
        pub_schedule_early = _read_json(_PUB_SCHEDULE_PATH)
        ep_match = publisher_email.identify_episode(
            subject, f"{text_body}\n{html_body}", pub_schedule_early.get("episodes", [])
        )

        missing = []
        if not apple_url:
            missing.append("Apple Podcasts URL")
        if not spotify_url:
            missing.append("Spotify URL")
        if not ep_match:
            missing.append("matching episode (by EP number or title)")
        if missing:
            raise PermanentFailure(
                f"PUBLISH_FINALIZE: could not process publish email: {', '.join(missing)}. subject={subject!r}"
            )

        episode_number = int(ep_match["episode_number"])

        logger.info(
            "publish_finalize: parsed publish email — E%d apple=%s spotify=%s mm=%s",
            episode_number,
            apple_url,
            spotify_url,
            mm_url,
        )

    # ── Step 2 — Identify episode in pub_schedule ──────────────────────────────
    run_ledger.step("2", "identify")
    pub_schedule = _read_json(_PUB_SCHEDULE_PATH)
    ep_entry = None
    for ep in pub_schedule.get("episodes", []):
        if ep.get("episode_number") == episode_number and ep.get("drive_folder_id"):
            ep_entry = ep
            break

    if not ep_entry:
        if trigger == "reprocess":
            # Reprocess path: episode predates pub_schedule or was never recorded.
            # Find the Drive folder by episode code prefix and build a stub entry.
            ep_folder = drive_client.find_episode_folder(f"E{episode_number}")
            if not ep_folder:
                raise PermanentFailure(
                    f"PUBLISH_FINALIZE reprocess: no Drive folder found for E{episode_number} "
                    f"— expected folder named E{episode_number}-* in the episodes Drive folder"
                )
            ep_entry = {
                "episode_number": episode_number,
                "episode_code": f"E{episode_number}",
                "season_episode_code": "TBD",
                "slug": "",
                "drive_folder_id": ep_folder["id"],
                "episode_title": "TBD",
                "guest_name": "Guest",
                "guest_email": "",
                "calendar_event_id": "",
            }
            logger.info(
                "publish_finalize: reprocess stub entry for E%d — Drive folder %s",
                episode_number,
                ep_folder["id"],
            )
        else:
            raise PermanentFailure(
                f"PUBLISH_FINALIZE: no pub_schedule entry with drive_folder_id for episode {episode_number}"
            )

    episode_code = ep_entry["episode_code"]  # "E26"
    run_ledger.bind(episode=episode_code)
    episode_title = ep_entry.get("episode_title", "TBD")
    season_ep_code = ep_entry.get("season_episode_code", "S?E?")
    slug = ep_entry.get("slug", "")
    episode_folder_id = ep_entry["drive_folder_id"]
    calendar_event_id = ep_entry.get("calendar_event_id", "")
    guest_name = ep_entry.get("guest_name") or "Guest"
    guest_email = ep_entry.get("guest_email") or ""

    episode_folder_url = f"https://drive.google.com/drive/folders/{episode_folder_id}"
    logger.info(
        "publish_finalize: episode identified — %s (%s) title=%r guest=%s",
        episode_code,
        season_ep_code,
        episode_title,
        guest_name,
    )

    # ── TRIG-03 — a publisher email for an episode Phase 2 already finished ────
    # Decided HERE, in the worker, against the schedule as it stands when the job runs: the single
    # worker serialises this behind any visuals run. A finished episode never runs Phase 2 again
    # (E33, job 142, 2026-10-08: a second thank-you draft, re-rendered reels, regenerated captions).
    run_ledger.step("2b", "route_late_email")
    if not (from_email and ep_entry.get("pipeline_done")):
        run_ledger.skipped("not a late email for a finished episode")
    if from_email and ep_entry.get("pipeline_done"):
        still_show = _links_pending(ep_entry.get("apple_url") or "", ep_entry.get("spotify_url") or "")
        if not (ep_entry.get("episode_links_pending") or still_show):
            note = f"publisher email for {episode_code}: Phase 2 already done with episode links — nothing to do"
            logger.info("publish_finalize: %s", note)
            _prepend_standup(episode_code, f"[NO-OP] {note}")
            return
        _links_only(
            ep_entry=ep_entry,
            episode_code=episode_code,
            episode_number=episode_number,
            apple_url=apple_url,
            spotify_url=spotify_url,
            mm_url=mm_url,
            message_id=message_id,
            subject=subject,
            body_text=f"{text_body}\n{html_body}",
        )
        return

    # ── Step 3 — Check visual assets ──────────────────────────────────────────
    run_ledger.step("3", "visuals")
    folder_files = drive_client.list_folder(episode_folder_id)
    tile_file = _find_visual(folder_files, "tile")
    reel_file = _find_visual(folder_files, "reel")

    if (not tile_file or not reel_file) and (reels_only or cards_only):
        # A narrow reprocess changes nothing but its one surface: it never parks a finished episode as "waiting for
        # visuals" (that would let a later Drive change resume a FULL Phase 2), never alerts, never writes the schedule
        # (Toby, #74 C1).
        raise PermanentFailure(
            f"{episode_code}: the tile or reel image is missing from the episode folder; a "
            f"{'cards' if cards_only else 'reels'}-only reprocess needs both. Nothing was changed."
        )
    if not tile_file or not reel_file:
        missing_visuals = []
        if not tile_file:
            missing_visuals.append(f"E{episode_number}-firstname-tile.jpg")
        if not reel_file:
            missing_visuals.append(f"E{episode_number}-firstname-reel.jpg")

        msg_body = (
            f"Episode {episode_code} ({episode_title}) is live on Apple + Spotify "
            f"but Phase 2 cannot run until these files are in the Drive episode folder:\n\n"
            + "\n".join(f"  • {f}" for f in missing_visuals)
            + f"\n\nDrive folder: {episode_folder_url}\n\n"
            f"Once you drop them in, the pipeline resumes automatically."
        )

        # Notify John by email
        gmail_client.send_pipeline_alert(
            to=_PIPELINE_ALERT_EMAIL,
            subject=f"Action needed: {episode_code} visuals missing — {episode_title}",
            body=msg_body,
        )

        # Write standup entry
        _prepend_standup(
            episode_code,
            f"[BLOCKED] Waiting for tile.jpg + reel.jpg before Phase 2 can run.\n"
            f"  Missing: {', '.join(missing_visuals)}\n"
            f"  Drive folder: {episode_folder_url}",
        )

        # Store mm_context in pub_schedule so the Drive watch resume path can find it
        for ep in pub_schedule.get("episodes", []):
            if ep.get("episode_number") == episode_number and ep.get("drive_folder_id"):
                ep["status"] = "waiting_for_visuals"
                ep["pending_mm_context"] = {
                    "apple_url": apple_url,
                    "spotify_url": spotify_url,
                    "mm_url": mm_url,
                    "episode_number": episode_number,
                    "message_id": message_id,
                    "received_at": datetime.now(timezone.utc).isoformat(),
                }
                break
        pub_schedule["updated_at"] = datetime.now(timezone.utc).isoformat()
        _write_json(_PUB_SCHEDULE_PATH, pub_schedule)

        logger.info(
            "publish_finalize: %s waiting for visuals — notified %s, standup updated",
            episode_code,
            _PIPELINE_ALERT_EMAIL,
        )
        run_ledger.skipped("waiting for visuals")
        return  # job done (not failed) — resume when Drive watch fires

    logger.info("publish_finalize: visuals present — tile=%s reel=%s", tile_file["name"], reel_file["name"])

    # ── Steps 4–16: Full content production ───────────────────────────────────
    # All work happens in a temp directory, cleaned up in finally. It lives on
    # DISK, not in /tmp — /tmp on the server is a 1.9 GB tmpfs (RAM) and this dir
    # holds the episode audio, WAV clips and rendered MP4s while WhisperX is
    # simultaneously asking for ~1.8 GB. See rockstar/ops/workspace.py.
    work_dir = workspace.make_work_dir(f"rockstar-{episode_code}-pf-")
    logger.info("publish_finalize: work dir %s", work_dir)

    try:
        _produce_content(
            work_dir=work_dir,
            episode_code=episode_code,
            episode_number=episode_number,
            episode_title=episode_title,
            season_ep_code=season_ep_code,
            slug=slug,
            episode_folder_id=episode_folder_id,
            episode_folder_url=episode_folder_url,
            folder_files=folder_files,
            tile_file=tile_file,
            reel_file=reel_file,
            calendar_event_id=calendar_event_id,
            guest_name=guest_name,
            guest_email=guest_email,
            apple_url=apple_url,
            spotify_url=spotify_url,
            mm_url=mm_url,
            message_id=message_id,
            pub_schedule=pub_schedule,
            trigger=trigger,
            reels_only=reels_only,
            only_quotes=only_quotes,
            cards_only=cards_only,
        )
    finally:
        shutil.rmtree(work_dir, ignore_errors=True)
        logger.info("publish_finalize: cleaned up %s", work_dir)


# Folders an operator archives old artifacts into, inside an episode folder (e.g.
# "_superseded-2026-07-21", E32's July Round 1). They are HISTORY, not input.
_ARCHIVE_FOLDER_PREFIX = "_superseded"


def _is_archive_folder(f: dict) -> bool:
    return "folder" in f.get("mimeType", "") and f.get("name", "").startswith(_ARCHIVE_FOLDER_PREFIX)


def _gather_files(folder_files: list[dict], list_folder) -> tuple[list[dict], dict]:
    """(extended_files, file_map) for an episode folder: root + immediate subfolders.

    This handles artifacts that ended up in a local/ or transcripts/ subfolder from a
    manual local run or partial earlier pipeline run. Visuals (_find_visual) always use
    root-only folder_files — visuals belong in the root, never in subfolders.

    An ARCHIVE subfolder (`_superseded*`) is skipped. Without that, its files join the
    name → id map, and two things go wrong (E32 re-run, 2026-09): an archived BINARY
    apple_summary.md / quotes.json outranks John's hand-edited Google-Doc copy in the root
    (binaries win pass 1 below, wherever they live), and _drive_replace would DELETE the
    archived faq.md when the root has none.

    file_map resolves two collisions, in priority order:
      1. Google-Docs editor files (mimeType vnd.google-apps.*) are NOT downloadable via
         alt=media — they 403. When a same-named binary exists (e.g. an uploaded
         apple_summary.md that Drive ALSO auto-converted into a Doc), the binary must win.
         This 403 is exactly what crashed the first E28 reprocess (2026-06-16).
      2. Root vs subfolder duplicates — root wins.
    First pass takes binaries only; second pass fills any name that exists solely as a
    Doc (best-effort — still surfaced loudly if undownloadable).
    """
    extended_files = list(folder_files)
    for f in folder_files:
        if "folder" not in f.get("mimeType", ""):
            continue
        if _is_archive_folder(f):
            logger.info("publish_finalize: skipping archive subfolder %r", f["name"])
            continue
        try:
            sub_files = list_folder(f["id"])
            extended_files.extend(sub_files)
            logger.debug("publish_finalize: loaded subfolder %r (%d files)", f["name"], len(sub_files))
        except Exception as exc:
            logger.warning("publish_finalize: could not list subfolder %r: %s", f["name"], exc)
            run_ledger.anomaly("subfolder not listed")  # its files are missing from this run (OBS-02)

    file_map = {}
    for f in reversed(extended_files):  # root processed last → overrides subfolder dupes
        if "vnd.google-apps" in f.get("mimeType", ""):
            continue
        file_map[f["name"]] = f["id"]
    for f in reversed(extended_files):
        file_map.setdefault(f["name"], f["id"])
    return extended_files, file_map


def _produce_content(
    work_dir: Path,
    episode_code: str,
    episode_number: int,
    episode_title: str,
    season_ep_code: str,
    slug: str,
    episode_folder_id: str,
    episode_folder_url: str,
    folder_files: list[dict],
    tile_file: dict,
    reel_file: dict,
    calendar_event_id: str,
    guest_name: str,
    guest_email: str,
    apple_url: str,
    spotify_url: str,
    mm_url: str,
    message_id: str,
    pub_schedule: dict,
    trigger: str = "gmail",
    reels_only: bool = False,
    only_quotes: list[str] | None = None,
    cards_only: bool = False,
) -> None:
    """Steps 4–16: download → compose → render → upload → draft → finalize.

    cards_only: Step 4's downloads, Step 5c (one title per quote), Step 12b (the card set) and nothing else: no
    FAQ, blog, reels, thank-you, calendar or schedule change. card_step never overwrites a cards/ that has files.

    reels_only: run only the reel path (Steps 4, 7a–10.5, and a surgical Step 12
    that replaces reel_*.mp4 in the existing Drive reels folder). Blog, FAQ,
    captions, thank-you draft, and calendar are NOT regenerated — Claude compose
    is non-deterministic, so regenerating would REPLACE existing artifacts with
    different text, not restore them (PP-8: that's a regression, not a rerun).
    """
    # NOTE: the title gate is NOT run here on the schedule title. apple_summary
    # (the human-review surface) wins, so we resolve the final title from it first
    # (see "title source of truth" below) and gate THAT — otherwise a schedule
    # title of "TBD" would hard-fail before the hand-edited summary could rescue it.
    # The gate still runs before any render/upload, just after title resolution.

    # Build file map from root + immediate subfolders.
    # This handles artifacts that ended up in a local/ or transcripts/ subfolder
    # from a manual local run or partial earlier pipeline run.
    # Visuals (_find_visual) always use root-only folder_files — visuals belong
    # in the root, never in subfolders.
    # ── Step 4 — Download artifacts from Drive ─────────────────────────────────
    # The step starts before the subfolder listing, so a listing that fails is recorded on step 4 (OBS-02).
    run_ledger.step("4", "download")
    extended_files, file_map = _gather_files(folder_files, drive_client.list_folder)

    # transcript_fast.txt
    transcript_file = file_map.get("transcript_fast.txt") or _find_file_by_pattern(
        folder_files, r"transcript_fast\.txt$", re.IGNORECASE
    )
    if not transcript_file:
        raise RuntimeError(f"{episode_code}: transcript_fast.txt not found in Drive folder")
    transcript_path = work_dir / "transcript_fast.txt"
    drive_client.download_file(
        transcript_file if isinstance(transcript_file, str) else transcript_file["id"],
        transcript_path,
    )
    transcript_text = transcript_path.read_text(encoding="utf-8")
    logger.info("publish_finalize: transcript %d chars", len(transcript_text))

    # quotes.json
    quotes_file_id = file_map.get("quotes.json")
    if not quotes_file_id:
        raise RuntimeError(f"{episode_code}: quotes.json not found in Drive folder")
    quotes_path = work_dir / "quotes.json"
    drive_client.download_file(quotes_file_id, quotes_path)
    quotes_data = json.loads(quotes_path.read_text(encoding="utf-8"))
    quotes = quotes_data.get("quotes", [])
    logger.info("publish_finalize: %d quotes loaded", len(quotes))

    # apple_summary.md
    apple_file_id = file_map.get("apple_summary.md")
    if not apple_file_id:
        raise RuntimeError(f"{episode_code}: apple_summary.md not found in Drive folder")
    apple_summary_path = work_dir / "apple_summary.md"
    drive_client.download_file(apple_file_id, apple_summary_path)
    apple_summary_text = apple_summary_path.read_text(encoding="utf-8")

    # ── Guest name: the reviewed summary fills a missing one ─────
    # With no form answer the schedule has no guest name; apple_summary.md's reviewed "About ⟨name⟩" fills it: the
    # guest's for a guest episode, the host's for a solo one, so the reel gate can tell the two apart.
    # log: docs/carry-forward/2026-10-13-remodel.md#guest-match
    guest_name = _guest_from_summary(guest_name, apple_summary_text, episode_code)

    # ── Title source of truth: apple_summary WINS (ADR-0009) ───────────────────
    # apple_summary.md is the human-review surface — John edits it before the
    # episode goes to the publisher. So its title overrides the Phase-1 schedule
    # title for the reels AND the blog. Falls back to the schedule title only if
    # the summary yields no real title. Then gate the FINAL title we'll render.
    parsed_title = _title_from_apple_summary(apple_summary_text)
    if parsed_title and content_gates.is_real_title(parsed_title):
        if parsed_title != episode_title:
            logger.info(
                "publish_finalize: title from apple_summary overrides schedule: %r (was %r)",
                parsed_title,
                episode_title,
            )
        episode_title = parsed_title
    else:
        logger.info(
            "publish_finalize: apple_summary has no usable title (%r) — keeping schedule title %r",
            parsed_title,
            episode_title,
        )
    _assert_real_title(episode_title, episode_code)

    # tile.* and reel.*
    tile_local = work_dir / tile_file["name"]
    # REEL-08: every reel image in the root (one per speaker), the first one keeps the old name `reel_local`.
    reel_locals: dict[str, Path] = {}
    for rf in episode_files.reel_images(folder_files):
        rp = work_dir / rf["name"]
        drive_client.download_file(rf["id"], rp)
        reel_locals[rf["id"]] = rp
    reel_local = work_dir / reel_file["name"]
    drive_client.download_file(tile_file["id"], tile_local)
    drive_client.download_file(reel_file["id"], reel_local)
    logger.info("publish_finalize: downloaded tile=%s reel=%s", tile_local.name, reel_local.name)

    # E{N}-*.m4a audio. A cards-only run never reads it (Toby, #74 M1): no download, no retry on a missing file.
    audio_local = None
    if not cards_only:
        ep_prefix = episode_code.lower() + "-"
        audio_file = None
        for f in folder_files:
            name = f["name"]
            if name.lower().startswith(ep_prefix) and Path(name).suffix.lower() in _AUDIO_EXTENSIONS:
                audio_file = f
                break
        if not audio_file:
            raise RuntimeError(f"{episode_code}: no {episode_code}-*.m4a audio found in Drive folder")
        audio_local = work_dir / audio_file["name"]
        drive_client.download_file(audio_file["id"], audio_local)
        logger.info("publish_finalize: downloaded audio=%s", audio_local.name)

    # ── Step 5 — (retired) ─────────────────────────────────────────────────────
    # The blog URL used to be DERIVED here from the title — a guess, and a wrong guess
    # already shipped once (BLOG-01). It now comes back from Tailor in Step 6 (AC-6).
    blog_post_url = ""

    if cards_only:
        # The card set alone: the titles first (the cards print them), then the card step. Lengths don't matter here.
        run_ledger.step("5c", "quote_titles")
        quotes = _fix_quote_titles(
            quotes, quotes_data, quotes_path, quotes_file_id, episode_folder_id, episode_code, episode_title
        )
        run_ledger.step("12b", "quote_cards")
        cards_status = card_step.build_cards(
            work_dir=work_dir,
            episode_code=episode_code,
            episode_number=episode_number,
            slug=slug,
            episode_title=episode_title,
            quotes_path=quotes_path,
            apple_summary_path=apple_summary_path,
            images=[tile_local, reel_local, *reel_locals.values()],
            episode_folder_id=episode_folder_id,
            drive_client=drive_client,
            alert=_alert,
            standup=_prepend_standup,
        )
        logger.info("publish_finalize: cards-only — %s; nothing else touched", cards_status)
        _record_cards_status(cards_status)
        if cards_status.startswith("failed"):
            # The run's one job didn't happen: the job fails (card_step has already alerted with the cause), never a
            # quiet "done" (Toby, #74 M2).
            raise PermanentFailure(f"{episode_code}: cards-only reprocess: {cards_status}")
        return

    # ── Step 5b — the clip ceiling, before any spend (CLIP-01c AC 3, 10, 11) ───
    # E13 spent faq_blog and ~385 s of alignment five times, then died in step 8. Phase 1's lengths are in quotes.json
    # (tape_check), so the check runs here, before step 6 and 7a-0. A quote without one is checked after alignment.
    run_ledger.step("5b", "clip_ceiling")
    limits = _clip_limits(episode_code)
    cleared = clip_limits.clear_bare_long_form(quotes)  # a hand-edited bare flag: one rule for every reader below
    if cleared:
        logger.warning("publish_finalize: long_form without a reason, cleared: %s", ", ".join(cleared))
        run_ledger.record("long_form_cleared", ids=cleared)
        run_ledger.anomaly("long_form without a reason, cleared")
        quotes_data["quotes"] = quotes
        quotes_path.write_text(json.dumps(quotes_data, indent=2, ensure_ascii=False), encoding="utf-8")
    to_render = [q for q in quotes if not only_quotes or q.get("id") in only_quotes]
    over, unmeasured = clip_limits.before_spend(to_render, limits)
    run_ledger.record(
        "clip_ceiling",
        ceiling=limits.as_dict(),
        unmeasured=unmeasured,
        lengths={str(q.get("id")): clip_limits.span_sec(q) for q in to_render},
    )
    if unmeasured:
        logger.info(
            "publish_finalize: no Phase 1 length for %s — checked on the aligned window after 7a", ", ".join(unmeasured)
        )
    _clip_guard(over, episode_code, "before the FAQ, the blog and alignment")

    # ── Step 5c — one title per quote (TITLE-02) ──────────────────────────────
    # Round 1 makes every heading pass the cover's rules; an episode drafted before that rule gets the same fix here,
    # before the blog prints the headings and the cards take them as cover titles. Never a stop: a heading that fails
    # is rewritten by the model or repaired by code, and the change is said in the standup.
    run_ledger.step("5c", "quote_titles")
    quotes = _fix_quote_titles(
        quotes, quotes_data, quotes_path, quotes_file_id, episode_folder_id, episode_code, episode_title
    )

    # ── Step 6 — faq.md + the Tailor blog post (BLOG-02b) ─────────────────────
    run_ledger.step("6", "faq_blog")
    episode_metadata = {
        "episode_number": episode_number,
        "episode_code": episode_code,
        "season_episode_code": season_ep_code,
        "slug": slug,
        "guest_name": guest_name,
        "blog_post_url": blog_post_url,
        "mm_url": mm_url,
    }

    if reels_only:
        logger.info("publish_finalize: reels-only — skipping faq.md + the blog post")
        run_ledger.skipped("reels_only")
    else:
        faq_text = _compose_and_upload_faq(
            work_dir=work_dir,
            transcript_text=transcript_text,
            apple_summary_text=apple_summary_text,
            episode_metadata=episode_metadata,
            file_map=file_map,
            episode_folder_id=episode_folder_id,
        )
        blog_post_url = _write_blog_post(
            work_dir=work_dir,
            episode_code=episode_code,
            episode_number=episode_number,
            episode_title=episode_title,
            apple_summary_text=apple_summary_text,
            quotes=quotes,
            faq_text=faq_text,
            apple_url=apple_url,
            spotify_url=spotify_url,
            tile_local=tile_local,
            tile_file=tile_file,
            file_map=file_map,
            episode_folder_id=episode_folder_id,
        )
        episode_metadata["blog_post_url"] = blog_post_url
        logger.info("publish_finalize: blog_post_url=%s (from the API)", blog_post_url)

    # ── Step 7a — Populate quote timestamps from WhisperX transcript ─────────────
    # Brand Team produces quotes with transcript_start_ms / transcript_end_ms = 0.
    # lookup_quote_timestamps.js fuzzy-matches quote text against segment timestamps
    # and fills them in. Also adds the 'index' and 'topic_slug' fields that
    # extract_quote_clips.sh expects.
    quotes, quotes_with_words, reel_mp4s, reels_dir = _produce_reels(
        apple_url=apple_url,
        audio_file=audio_file,
        audio_local=audio_local,
        episode_code=episode_code,
        episode_number=episode_number,
        episode_title=episode_title,
        extended_files=extended_files,
        file_map=file_map,
        folder_files=folder_files,
        guest_name=guest_name,
        limits=limits,
        mm_url=mm_url,
        only_quotes=only_quotes,
        quotes=quotes,
        quotes_data=quotes_data,
        quotes_path=quotes_path,
        reel_local=reel_local,
        reel_locals=reel_locals,
        reels_only=reels_only,
        season_ep_code=season_ep_code,
        slug=slug,
        spotify_url=spotify_url,
        work_dir=work_dir,
    )

    # ── Step 11 — Generate SEO captions ────────────────────────────────────────
    _caption_and_upload_reels(
        apple_url=apple_url,
        blog_post_url=blog_post_url,
        episode_code=episode_code,
        episode_folder_id=episode_folder_id,
        episode_metadata=episode_metadata,
        episode_title=episode_title,
        folder_files=folder_files,
        only_quotes=only_quotes,
        quotes=quotes,
        quotes_with_words=quotes_with_words,
        reel_mp4s=reel_mp4s,
        reels_dir=reels_dir,
        reels_only=reels_only,
        spotify_url=spotify_url,
    )

    # ── Step 12b — Quote cards (CARD-05, ADR-0015) ────────────────────────────
    # Slides, covers and captions in vendored IBM Plex, into Drive cards/. Alert and
    # continue on any failure; never overwrites a cards/ that already has files; the
    # reel path is untouched. reels_only reprocesses skip it.
    run_ledger.step("12b", "quote_cards")
    if not reels_only:
        cards_status = card_step.build_cards(
            work_dir=work_dir,
            episode_code=episode_code,
            episode_number=episode_number,
            slug=slug,
            episode_title=episode_title,
            quotes_path=quotes_path,
            apple_summary_path=apple_summary_path,
            images=[tile_local, reel_local, *reel_locals.values()],
            episode_folder_id=episode_folder_id,
            drive_client=drive_client,
            alert=_alert,
            standup=_prepend_standup,
        )
        logger.info("publish_finalize: cards — %s", cards_status)
        _record_cards_status(cards_status)

    # ── Step 13 — Fill + create thank-you Gmail draft (deterministic, ADR-0010) ─
    # ⚠️ DRAFT ONLY — NEVER AUTO-SENT (hard constraint)
    run_ledger.step("13", "thank_you")
    if reels_only:
        logger.info(
            "publish_finalize: reels-only — skipping thank-you draft + calendar; done. %s: %d reels replaced",
            episode_code,
            len(reel_mp4s),
        )
        run_ledger.skipped("reels_only")
        return
    # REEL-08 / John 2026-10-01: "skip it". When Heather is the featured guest there is nobody to thank.
    if _guest_is_host(guest_name):
        logger.info("publish_finalize: %s — Heather is the guest; thank-you draft skipped", episode_code)
        run_ledger.skipped("Heather is the guest")
        if _links_pending(apple_url, spotify_url):
            _links_pending_alert(episode_code, blog_post_url, "(none: Heather is the guest)")
    else:
        # DETERMINISTIC FILL (ADR-0010) — no model in the path. Every slot is a known
        # value here; thank_you.build_draft fills the template's own bytes. The old
        # anthropic_client.compose_thank_you round-trip is retired: on E29 the model
        # emitted its tool-call narration as the body (see TY-01/TY-02).
        logger.info("publish_finalize: filling thank-you template (deterministic)")
        ty = thank_you.build_draft(
            guest_name=guest_name,
            episode_title=episode_title,
            apple_url=apple_url,
            spotify_url=spotify_url,
            blog_url=blog_post_url,
            guest_email=guest_email,
        )
        ty_subject = ty["subject"]
        ty_body = ty["body"]

        # GATE before anything irreversible: never let transcript/model cruft (or a
        # drifted template) become a guest-facing draft (PQ-5). A deterministic fill
        # can't produce cruft, so a failure here is a real bug — fail loud, no draft.
        _assert_thank_you_wellformed(ty_body)

        if not thank_you.has_guest_email(guest_email):
            logger.info(
                "publish_finalize: guest_email missing for %s — drafting to Heather with flagged subject",
                episode_code,
            )

        # Upload thank_you.md (full Subject+body block) to Drive — delete prior versions first
        ty_path = work_dir / "thank_you.md"
        ty_path.write_text(ty["block"], encoding="utf-8")
        n = _drive_delete_all_by_name(folder_files, "thank_you.md")
        if n:
            logger.info("publish_finalize: deleted %d old thank_you.md(s)", n)
        drive_client.upload_file(ty_path, episode_folder_id, "thank_you.md", "text/plain")

        # Create Gmail draft (NEVER send — hard constraint).
        draft = gmail_client.create_draft(
            to=ty["to"],
            subject=ty_subject,
            body=ty_body,
        )
        # TRIG-03: record the draft as Gmail STORED it, so a late publisher email can tell whether a
        # person has touched it before it swaps in the real links.
        _record_ty_draft(episode_number, draft)
        logger.info("publish_finalize: thank-you draft created — to=%r subject=%r", ty["to"], ty_subject)
        _thank_you_ready_alert(episode_code, ty["to"], ty_subject, blog_post_url)
        if _links_pending(apple_url, spotify_url):
            _links_pending_alert(episode_code, blog_post_url, ty["to"])

    # ── Step 14 — Update calendar event to LIVE ────────────────────────────────
    # CAL-OFF follow-up (E32, 2026-10-01): with the switch off, an OLD event id (from before CAL-OFF) was
    # still marked LIVE. Off means no Calendar calls at all.
    run_ledger.step("14", "calendar")
    calendar_on = config.editorial_calendar_on()
    if reels_only:
        run_ledger.skipped("reels_only")  # a reels-only run carries no episode links to mark live
    elif calendar_event_id and calendar_on:
        _mark_calendar_live(calendar_event_id, apple_url, spotify_url, episode_code)
    elif calendar_on:
        logger.warning("publish_finalize: no calendar_event_id for %s — skipping", episode_code)
        run_ledger.skipped("no calendar_event_id")
    else:
        logger.info("publish_finalize: calendar event off (CAL-OFF) — step 14 skipped for %s", episode_code)
        run_ledger.skipped("calendar event off (CAL-OFF)")

    # ── Step 15 — Update publication_schedule.json ─────────────────────────────
    # A full reprocess with verified links completes Phase 2 and writes the schedule; a --reels-only run doesn't
    # (it replaces reels, it doesn't finish the episode). The merge never clobbers what an earlier real run recorded:
    # mm_url, message_id, and actual_live_date once known.
    # log: docs/carry-forward/2026-10-13-remodel.md#schedule
    run_ledger.step("15", "schedule")
    if not reels_only:
        pub_schedule = _read_json(_PUB_SCHEDULE_PATH)  # re-read (may have changed)
        matched = False
        for ep in pub_schedule.get("episodes", []):
            if ep.get("episode_number") == episode_number and ep.get("drive_folder_id"):
                _apply_phase2_completion(
                    ep,
                    apple_url=apple_url,
                    spotify_url=spotify_url,
                    mm_url=mm_url,
                    blog_post_url=blog_post_url,
                    message_id=message_id,
                    today=datetime.now(timezone.utc).date().isoformat(),
                    links_pending=_links_pending(apple_url, spotify_url),
                )
                matched = True
                break
        if matched:
            pub_schedule["updated_at"] = datetime.now(timezone.utc).isoformat()
            _write_json(_PUB_SCHEDULE_PATH, pub_schedule)
            logger.info("publish_finalize: pub_schedule updated — %s status=done", episode_code)
        else:
            # Reprocess can run on an episode that predates the schedule (a stub entry
            # was built in Step 2). Say so — silence here is what let the gap hide.
            logger.warning(
                "publish_finalize: no pub_schedule entry with drive_folder_id for %s — "
                "schedule NOT updated; reconcile by hand if this episode should be tracked",
                episode_code,
            )
            run_ledger.skipped("no schedule entry for this episode")
    else:
        logger.info("publish_finalize: reels-only — pub_schedule status untouched by design")
        run_ledger.skipped("reels_only")

    # ── Step 16 — Write .pipeline_done marker ─────────────────────────────────
    # Same reasoning as Step 15: a full reprocess finishes the episode, so it earns
    # the marker. `create_pipeline_done_marker` is idempotent, so re-running cannot
    # accumulate duplicates (E28's folder collected five before that was fixed).
    run_ledger.step("16", "done_marker")
    if not reels_only:
        drive_client.create_pipeline_done_marker(episode_folder_id)
        logger.info("publish_finalize: .pipeline_done ensured for %s", episode_code)
    else:
        logger.info("publish_finalize: reels-only — skipping .pipeline_done marker")
        run_ledger.skipped("reels_only")

    logger.info(
        "publish_finalize complete — %s (%s) blog=%s reels=%d",
        episode_code,
        season_ep_code,
        blog_post_url,
        len(reel_mp4s),
    )


def _caption_and_upload_reels(
    *,
    apple_url,
    blog_post_url,
    episode_code,
    episode_folder_id,
    episode_metadata,
    episode_title,
    folder_files,
    only_quotes,
    quotes,
    quotes_with_words,
    reel_mp4s,
    reels_dir,
    reels_only,
    spotify_url,
):
    """Steps 11–12: each reel's captions (Instagram, LinkedIn, YouTube), then the reels and their captions to Drive."""
    run_ledger.step("11", "seo_captions")
    caption_files: list[Path] = []
    if reels_only:
        logger.info("publish_finalize: reels-only — keeping existing captions on Drive")
        run_ledger.skipped("reels_only")
    else:
        logger.info("publish_finalize: generating SEO captions")
        captions = anthropic_client.compose_seo_captions(
            quotes=quotes_with_words if quotes_with_words else quotes,
            episode_title=episode_title,
            apple_url=apple_url,
            spotify_url=spotify_url,
            blog_post_url=blog_post_url,
            episode_metadata=episode_metadata,
        )

        # Write caption files: reels/reel_01_captions.md … reel_05_captions.md
        for idx, _mp4 in enumerate(reel_mp4s, 1):
            idx_str = str(idx)
            cap = captions.get(idx_str, {})
            if not cap:
                logger.warning("publish_finalize: no captions for reel %d — skipping caption file", idx)
                continue
            cap_path = reels_dir / f"reel_{idx:02d}_captions.md"
            # Append the music credit deterministically (idempotent) so the exact
            # attribution string is guaranteed — the model is told not to write one.
            instagram = (cap.get("instagram", "") or "").rstrip()
            if instagram and _IG_MUSIC_CREDIT not in instagram:
                instagram = f"{instagram}\n\n{_IG_MUSIC_CREDIT}"
            cap_path.write_text(
                f"## Instagram\n\n{instagram}\n\n"
                f"## LinkedIn\n\n{cap.get('linkedin', '')}\n\n"
                f"## YouTube\n\n{cap.get('youtube', '')}\n",
                encoding="utf-8",
            )
            caption_files.append(cap_path)
        logger.info("publish_finalize: %d caption files written", len(caption_files))

    # ── Step 12 — Upload reels + captions to Drive ─────────────────────────────
    run_ledger.step("12", "upload_reels")
    logger.info("publish_finalize: uploading reels to Drive")
    if reels_only:
        # Surgical replace: delete ONLY reel_*.mp4 inside the existing reels
        # folder, keep captions and anything hand-placed. The full path below
        # deletes the whole folder — fine on a fresh run, a regression here.
        reels_folder_id = None
        for f in folder_files:
            if f["name"] == "reels" and "folder" in f.get("mimeType", ""):
                reels_folder_id = f["id"]
                break
        if reels_folder_id:
            from googleapiclient.discovery import build as _build

            from rockstar.clients.google_auth import drive_credentials as _drive_creds

            _svc = _build("drive", "v3", credentials=_drive_creds(), cache_discovery=False)
            old_mp4s = _reels_to_replace(
                drive_client.list_folder(reels_folder_id), _reel_numbers(quotes) if only_quotes else None
            )
            for f in old_mp4s:
                _svc.files().delete(fileId=f["id"]).execute()
            if only_quotes:
                _flag_stale_captions(drive_client.list_folder(reels_folder_id), _reel_numbers(quotes), episode_code)
            logger.info(
                "publish_finalize: reels-only — deleted %d old reel mp4(s)%s, captions kept",
                len(old_mp4s),
                f" for {', '.join(only_quotes)}" if only_quotes else "",
            )
        else:
            reels_folder = drive_client.create_folder("reels", episode_folder_id)
            reels_folder_id = reels_folder["id"]
            logger.info("publish_finalize: reels-only — no existing reels folder, created one")
    else:
        n = _drive_delete_all_by_name(folder_files, "reels")
        if n:
            logger.info("publish_finalize: deleted %d old reels folder(s)", n)
        reels_folder = drive_client.create_folder("reels", episode_folder_id)
        reels_folder_id = reels_folder["id"]

    for mp4 in reel_mp4s:
        drive_client.upload_file(mp4, reels_folder_id, mp4.name, "video/mp4")
        logger.info("publish_finalize: uploaded %s", mp4.name)
    for cap_file in caption_files:
        drive_client.upload_file(cap_file, reels_folder_id, cap_file.name, "text/plain")
        logger.info("publish_finalize: uploaded %s", cap_file.name)


def _produce_reels(
    *,
    apple_url,
    audio_file,
    audio_local,
    episode_code,
    episode_number,
    episode_title,
    extended_files,
    file_map,
    folder_files,
    guest_name,
    limits,
    mm_url,
    only_quotes,
    quotes,
    quotes_data,
    quotes_path,
    reel_local,
    reel_locals,
    reels_only,
    season_ep_code,
    slug,
    spotify_url,
    work_dir,
):
    """Steps 7a–10.5: quote timestamps, forced alignment, clips, clip transcription, word timestamps, metadata,
    speaker backgrounds, render, the Instagram gate."""
    run_ledger.step("7a", "quote_timestamps")
    transcript_json_path = work_dir / "transcript_fast.json"
    transcript_json_file = file_map.get("transcript_fast.json") or _find_file_by_pattern(
        extended_files, r"transcript_fast\.json$", re.IGNORECASE
    )
    if transcript_json_file:
        drive_client.download_file(
            transcript_json_file if isinstance(transcript_json_file, str) else transcript_json_file["id"],
            transcript_json_path,
        )
        # ── Step 7a-0 — FORCED ALIGNMENT (REEL-05 / ADR 0003, ADR 0004) ──────────
        # lookup runs before the clips are cut, on transcript_fast.json, whose word times are interpolated: boundaries
        # land on ±0.5–1 s guesses and every inter-word gap is zero, so the lead-in clamp and the trailing guard can
        # never fire. align_episode.py recovers real per-word onsets by forced alignment only (the text is known; no
        # re-transcription), which a 2-vCPU box can afford. A Phase 2 that can't align stops (REEL-11).
        # log: docs/carry-forward/2026-10-13-remodel.md#reels
        run_ledger.step("7a-0", "forced_alignment")
        aligned_json_path = _force_align(
            work_dir,
            episode_code,
            transcript_json_path,
            rerun=_rerun_command(episode_number, apple_url, spotify_url, mm_url, reels_only, only_quotes),
            reels_only=reels_only,
        )

        logger.info("publish_finalize: running lookup_quote_timestamps")
        lookup_cmd = [
            "node",
            _REELS_DIR / "lookup_quote_timestamps.js",
            "--quotes",
            str(quotes_path),
            "--transcript",
            str(transcript_json_path),
        ]
        lookup_cmd += ["--aligned", str(aligned_json_path)]
        _run_script(lookup_cmd, work_dir, "lookup_quote_timestamps")
        # Reload quotes after timestamp injection
        quotes_data = json.loads(quotes_path.read_text(encoding="utf-8"))
        quotes = quotes_data.get("quotes", [])
        logger.info("publish_finalize: timestamps populated for %d quotes", len(quotes))
    else:
        logger.warning(
            "publish_finalize: transcript_fast.json not found — skipping timestamp lookup "
            "(extract_quote_clips will warn on 0-timestamp quotes)"
        )
        run_ledger.skipped("transcript_fast.json not found")

    # The whole episode's quotes: the guest-featured gate and the background picker judge the episode, never the subset
    # a per-quote run renders (Toby, QUOTE-03 review: a host-only subset failed the gate; a subset hid a co-guest).
    episode_quotes = quotes
    if only_quotes:
        # QUOTE-03: narrow the work copy to the named quotes, so steps 7–10 cut, transcribe and render only theirs.
        quotes = _select_quotes(quotes_path, only_quotes, episode_code)

    # ── Step 7 — Extract quote audio clips ─────────────────────────────────────
    run_ledger.step("7", "extract_clips")
    # CLIP-01c: the aligned windows are the reel's body and the clip WhisperX gets: checked before anything is cut.
    # The margin's evidence (Toby's review): Phase 1's span beside the aligned window, for every quote, every run.
    run_ledger.record(
        "span_vs_aligned", quotes=clip_limits.span_vs_aligned(quotes), margin_s=clip_limits.SPAN_SHORT_SEC
    )
    _clip_guard(clip_limits.after_alignment(quotes, limits), episode_code, "after alignment, before the clips")
    logger.info("publish_finalize: extracting quote clips")
    # Script interface: extract_quote_clips.sh <episode_folder> <audio_filename>
    # We use work_dir as the episode_folder since all artifacts are there.
    _run_script(
        ["bash", _SCRIPTS_DIR / "extract_quote_clips.sh", work_dir, audio_file["name"]],
        work_dir,
        "extract_quote_clips",
    )
    clips_dir = work_dir / "clips"
    clips_manifest = clips_dir / "clips_manifest.json"
    if not clips_manifest.exists():
        raise RuntimeError(f"{episode_code}: extract_quote_clips.sh did not produce clips/clips_manifest.json")
    logger.info("publish_finalize: clips extracted — manifest at %s", clips_manifest)

    # ── Step 8 — Transcribe clips for word timestamps ──────────────────────────
    run_ledger.step("8", "transcribe_clips")
    # CLIP-01c AC 10: each cut clip against the box's measured limit, before WhisperX loads (transcribe_clips.sh
    # refuses too, for a run by hand).
    _clip_guard(
        clip_limits.manifest_problems(json.loads(clips_manifest.read_text(encoding="utf-8")), limits),
        episode_code,
        "before WhisperX",
    )
    logger.info("publish_finalize: transcribing clips (whisperx large-v3)")
    # Script interface: transcribe_clips.sh <episode_folder>
    _run_script(
        ["bash", _SCRIPTS_DIR / "transcribe_clips.sh", work_dir],
        work_dir,
        "transcribe_clips",
    )
    logger.info("publish_finalize: clip transcription done")

    # ── Step 9 — Inject word timestamps into quotes.json ──────────────────────
    run_ledger.step("9", "inject_timestamps")
    logger.info("publish_finalize: injecting word timestamps")
    # Script interface: node inject_word_timestamps.js --quotes <path> --clips-dir <path>
    _run_script(
        [
            "node",
            _REELS_DIR / "inject_word_timestamps.js",
            "--quotes",
            str(quotes_path),
            "--clips-dir",
            str(clips_dir),
        ],
        work_dir,
        "inject_word_timestamps",
    )
    # Reload quotes after injection
    quotes_with_words = json.loads(quotes_path.read_text(encoding="utf-8")).get("quotes", [])
    logger.info("publish_finalize: word timestamps injected into %d quotes", len(quotes_with_words))

    # ── Step 9b — Inject episode metadata into quotes.json for render_reel.js ──
    # render_reel.js reads quotes.json and expects a top-level "episode" object.
    # The Brand Team never writes this field — we inject it here.
    # render_reel.js uses: episode.number (writes "E{N}" to title card),
    #                       episode.title  (wrapped text in purple band),
    #                       episode.slug   (optional, for logging only)
    run_ledger.step("9b", "inject_metadata")
    quotes_data = json.loads(quotes_path.read_text(encoding="utf-8"))
    quotes_data["episode"] = {
        "number": episode_number,
        "title": episode_title,
        "slug": slug or f"e{episode_number}",
        "code": episode_code,
        "season_ep_code": season_ep_code,
    }
    quotes_path.write_text(json.dumps(quotes_data, indent=2, ensure_ascii=False), encoding="utf-8")
    logger.info(
        "publish_finalize: injected episode metadata into quotes.json (number=%d title=%r)",
        episode_number,
        episode_title,
    )

    # RULE GATE: an interview's reels must feature the guest, not be 100% host.
    _assert_guest_featured(episode_quotes if only_quotes else quotes, guest_name, episode_code)

    # ── Step 9c — REEL-08: each reel's background is its own speaker's image ───
    run_ledger.step("9c", "speaker_backgrounds")
    _assign_reel_backgrounds(
        quotes_path,
        folder_files,
        reel_locals,
        episode_code,
        all_speakers=[q.get("speaker") or "" for q in episode_quotes],
        named=bool(only_quotes),
    )

    # ── Step 10 — Render reel MP4s ─────────────────────────────────────────────
    run_ledger.step("10", "render_reels")
    logger.info("publish_finalize: rendering reels")
    reels_dir = work_dir / "reels"
    reels_dir.mkdir(exist_ok=True)

    # Script interface: node render_reel.js --quotes-json <path> --audio <path>
    #                     --background <path> --output-dir <path>
    render_cmd = [
        "node",
        _REELS_DIR / "render_reel.js",
        "--quotes-json",
        str(quotes_path),
        "--audio",
        str(audio_local),
        "--background",
        str(reel_local),
        "--output-dir",
        str(reels_dir),
    ]
    if only_quotes:
        # One render per named quote: `--reel NN` renders it even if it isn't a reel candidate (a person named it).
        for nn in _reel_numbers(quotes):
            _run_script([*render_cmd, "--reel", nn], work_dir, "render_reel")
    else:
        _run_script(render_cmd, work_dir, "render_reel")

    reel_mp4s = sorted(reels_dir.glob("reel_*.mp4"))
    logger.info("publish_finalize: %d reel MP4s rendered", len(reel_mp4s))

    # ── Step 10.5 — Instagram compliance gate ──────────────────────────────────
    # render_reel.js checks each reel; the job re-checks as defense in depth: nothing reaches Drive unless every reel
