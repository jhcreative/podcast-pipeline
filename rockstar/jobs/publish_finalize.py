# ── subprocess runner ────────────────────────────────────────────────────────────


class ScriptFailed(RuntimeError):
    """A script exited non-zero. Still a RuntimeError (the worker retries it); carries the end of its stderr, where a
    Python traceback puts the line that matters (REEL-11: the alignment alert quotes it)."""

    def __init__(self, message: str, stderr: str):
        super().__init__(message)
        self.stderr_tail = "\n".join((stderr or "").strip().splitlines()[-8:])


def _run_script(cmd: list, work_dir: Path, label: str) -> None:
    """
    Run an external script.  Logs stdout/stderr and raises RuntimeError on
    non-zero exit (worker's exponential back-off handles transient failures).
    """
    logger.info("%s: %s", label, " ".join(str(c) for c in cmd))
    oom_before = oom_watch.oom_kills()
    result = subprocess.run(
        [str(c) for c in cmd],
        cwd=str(work_dir),
        capture_output=True,
        text=True,
    )
    if result.stdout:
        logger.info("%s stdout: %.800s", label, result.stdout)
    if result.stderr:
        logger.warning("%s stderr: %.800s", label, result.stderr)
    if result.returncode != 0:
        if oom_watch.ran_out(oom_before):
            # CLIP-01a: the same input runs out of memory again, so a retry only rewrites the FAQ and the draft
            # and dies in the same place (E13, five times). Say so once and stop.
            where = run_ledger.current_step() or label
            clip = oom_watch.clip_in_progress(result.stdout, Path(work_dir) / "clips" / "clips_manifest.json")
            reason = f"out of memory in step {where}" + (f" on {clip}" if clip else "")
            ep = run_ledger.episode() or "E?"
            _alert(
                f"{ep}: Phase 2 stopped — {reason}",
                f"{reason}.\n\nThe kernel's OOM killer stopped it (cgroup memory.events oom_kill grew); "
                f"the script saw exit {result.returncode}. Not retried: the same input runs out again.\n",
            )
            raise PermanentFailure(reason)
        raise ScriptFailed(f"{label} failed (exit {result.returncode}): {result.stderr[:300]}", result.stderr)


